  UNION ALL
  SELECT '000000316', '000007299' FROM dual
  UNION ALL
  SELECT '000000317', '000007300' FROM dual
  UNION ALL
  SELECT '000000318', '000007301' FROM dual
  UNION ALL
  SELECT '000000319', '000007302' FROM dual
  UNION ALL
  SELECT '000000320', '000007303' FROM dual
)
SELECT m.sec_viejo,
       m.sec_nuevo,
       r.ID                                                        AS rtv2_id,
       r.ESTADO,
       r.ESTADOEMISION,
       CASE WHEN r.SECUENCIAL = m.sec_viejo THEN 'VIEJO'
            WHEN r.SECUENCIAL = m.sec_nuevo THEN 'NUEVO'
            ELSE 'REVISAR:' || r.SECUENCIAL END                    AS est_secuencial,
       CASE WHEN r.NUMERO = '001-001-' || m.sec_viejo THEN 'VIEJO'
            WHEN r.NUMERO = '001-001-' || m.sec_nuevo THEN 'NUEVO'
            ELSE 'REVISAR:' || r.NUMERO END                        AS est_numero,
       CASE WHEN r.CLAVE LIKE '%001001' || m.sec_viejo || '%' THEN 'VIEJO'
            WHEN r.CLAVE LIKE '%001001' || m.sec_nuevo || '%' THEN 'NUEVO'
            ELSE 'REVISAR' END                                     AS est_clave,
       REGEXP_COUNT(NVL(r.CLAVE, '~'), m.sec_viejo)                AS veces_sec_viejo_en_clave,
       CASE WHEN r.AUTORIZACION LIKE '%001001' || m.sec_viejo || '%' THEN 'VIEJO'
            WHEN r.AUTORIZACION LIKE '%001001' || m.sec_nuevo || '%' THEN 'NUEVO'
            ELSE 'REVISAR' END                                     AS est_autorizacion,
       REGEXP_COUNT(NVL(r.AUTORIZACION, '~'), m.sec_viejo)         AS veces_sec_viejo_en_aut,
       r.ASIENTO                                                   AS asnt_codigo,
       a.ASNTUSRO,
       CASE WHEN a.ASNTOBSR LIKE '%' || m.sec_viejo || '%' THEN 'VIEJO'
            WHEN a.ASNTOBSR LIKE '%' || m.sec_nuevo || '%' THEN 'NUEVO'
            ELSE 'REVISAR' END                                     AS est_obsr,
       (SELECT COUNT(*) FROM CNT.DTAS d
         WHERE d.ASNTCDGO = r.ASIENTO AND d.PLNNCDGO = 9677
           AND d.DTASDSCR LIKE '%001-001-' || m.sec_viejo || '%')  AS dtas_con_viejo,
       (SELECT COUNT(*) FROM CNT.DTAS d
         WHERE d.ASNTCDGO = r.ASIENTO AND d.PLNNCDGO = 9677
           AND d.DTASDSCR LIKE '%001-001-' || m.sec_nuevo || '%')  AS dtas_con_nuevo,
       r.CLAVE,
       r.AUTORIZACION,
       a.ASNTOBSR
FROM   mapa m
JOIN   CBR.RTV2 r
       ON (   r.SECUENCIAL IN (m.sec_viejo, m.sec_nuevo)
           OR r.NUMERO IN ('001-001-' || m.sec_viejo, '001-001-' || m.sec_nuevo) )
LEFT JOIN CNT.ASNT a ON a.ASNTCDGO = r.ASIENTO
ORDER  BY m.sec_viejo;

