SELECT m.sec_viejo,
       m.sec_nuevo,
       COUNT(r.ID) AS filas_rtv2
FROM   mapa m
LEFT JOIN CBR.RTV2 r
       ON (   r.SECUENCIAL IN (m.sec_viejo, m.sec_nuevo)
           OR r.NUMERO IN ('001-001-' || m.sec_viejo, '001-001-' || m.sec_nuevo) )
GROUP  BY m.sec_viejo, m.sec_nuevo
ORDER  BY m.sec_viejo;

-- =====================================================================================
-- SECCIÓN 1b — DIAGNÓSTICO: estado actual campo por campo (VIEJO / NUEVO / REVISAR)
-- Sirve para ver qué retenciones quedaron a medias antes de tocar nada.
