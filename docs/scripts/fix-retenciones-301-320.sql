WITH mapa (sec_viejo, sec_nuevo) AS (
  SELECT '000000301', '000007276' FROM dual
  UNION ALL
  SELECT '000000302', '000007277' FROM dual
  UNION ALL
  SELECT '000000303', '000007278' FROM dual
