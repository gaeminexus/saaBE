-- =====================================================================================
-- CORRECCIÓN DE NUMERACIÓN DE 20 RETENCIONES ELECTRÓNICAS (RetencionV2 / CBR.RTV2)
-- Secuenciales de PRUEBAS 301..320  ->  secuenciales REALES 7276..7303 (con huecos)
--
-- Tablas afectadas (nombres verificados contra las entidades JPA del proyecto):
--   CBR.RTV2  : SECUENCIAL, NUMERO, CLAVE, AUTORIZACION   (fila de la retención)
--   CNT.ASNT  : ASNTOBSR, ASNTUSRO                        (asiento; RTV2.ASIENTO = ASNT.ASNTCDGO)
--   CNT.DTAS  : DTASDSCR                                  (detalle del asiento, solo PLNNCDGO = 9677)
--
-- CÓMO EJECUTAR (DBeaver):
--   0. DESACTIVAR AUTO-COMMIT en la conexión antes de empezar.
--   1. Ejecutar la SECCIÓN 1 (diagnóstico, solo lectura).
--        - 1a debe devolver EXACTAMENTE 1 fila RTV2 por cada una de las 20 retenciones.
--          Si alguna devuelve 0 o más de 1 -> NO CONTINUAR (habría que fijar por ID).
--        - En 1b, las columnas VECES_SEC_VIEJO_EN_* deben ser 0 o 1. Si alguna es > 1,
--          el bloque de 9 dígitos aparece más de una vez en esa clave -> NO CONTINUAR.
--   2. Ejecutar la SECCIÓN 2 (updates). Cada UPDATE es idempotente y por campo:
--      solo modifica si el campo todavía contiene el valor VIEJO; los campos ya
--      corregidos a mano no se tocan.
--   3. Ejecutar la SECCIÓN 3 (verificación): todo debe salir 'NUEVO' y las consultas
--      de residuos deben devolver 0 filas.
--   4. Solo si la verificación está correcta: descomentar y ejecutar el COMMIT final.
--      Si algo está mal: ejecutar ROLLBACK.
--
-- NOTAS DE SEGURIDAD:
--   * En CLAVE/AUTORIZACION el reemplazo usa el bloque ANCLADO de 15 dígitos
--     '001001' + secuencial (establecimiento + ptoEmision + secuencial), no el
--     secuencial suelto de 9 dígitos, para eliminar el riesgo de reemplazar una
--     coincidencia accidental en otra parte de la clave.
--   * ADVERTENCIA: la clave de acceso del SRI termina en un dígito verificador
--     (módulo 11) calculado sobre los 48 dígitos anteriores, e incluye además el
--     dígito de ambiente. Reemplazar SOLO el bloque del secuencial (según la regla
--     indicada) deja el DV y el ambiente tal como estaban. Se implementa exactamente
--     la regla solicitada; validar contra los comprobantes reales autorizados por
--     el SRI antes del COMMIT.
-- =====================================================================================

