-- ---------------------------------------------------------------------
-- VERIFICACION — comparar DRC2 contra su gemelo DRV2
-- ---------------------------------------------------------------------
-- Debe devolver una fila por columna, con las dos definiciones lado a
-- lado y la marca 'DIFERENTE' donde no coincidan. Lo esperado es que la
-- unica diferencia relevante sea ninguna (los tipos deben ser iguales).

SELECT NVL(a.column_name, b.column_name) AS COLUMNA,
       a.data_type || '(' || NVL(TO_CHAR(a.data_length), '-') || ')' AS DRC2_PGS,
       b.data_type || '(' || NVL(TO_CHAR(b.data_length), '-') || ')' AS DRV2_CBR,
       CASE WHEN a.column_name IS NULL THEN 'FALTA EN DRC2'
            WHEN b.column_name IS NULL THEN 'SOBRA EN DRC2'
            WHEN a.data_type <> b.data_type OR NVL(a.data_length,0) <> NVL(b.data_length,0)
                 THEN 'DIFERENTE'
            ELSE 'ok' END AS COMPARACION
  FROM (SELECT column_name, data_type, data_length FROM all_tab_columns
         WHERE owner = 'PGS' AND table_name = 'DRC2') a
  FULL OUTER JOIN
       (SELECT column_name, data_type, data_length FROM all_tab_columns
         WHERE owner = 'CBR' AND table_name = 'DRV2') b
    ON a.column_name = b.column_name
 ORDER BY COMPARACION, COLUMNA;

