-- ---------------------------------------------------------------------
-- OPCION A (RECOMENDADA) — Copiar la estructura exacta de CBR.DRV2
-- ---------------------------------------------------------------------
-- Garantiza que los tipos y longitudes queden identicos a los del gemelo,
-- sin depender de que yo los haya transcrito bien. Requiere SELECT sobre
-- CBR.DRV2 (su usuario ya lo tiene: aparecio en la consulta de
-- ALL_OBJECTS). CTAS copia nombres, tipos y NOT NULL, pero NO copia la
-- PK, la identidad ni las FK: por eso se agregan despues.

CREATE TABLE PGS.DRC2 AS SELECT * FROM CBR.DRV2 WHERE 1 = 0;

-- CTAS no copia la identidad, y Oracle NO permite convertir una columna
-- existente en columna de identidad: 'MODIFY ID GENERATED AS IDENTITY'
-- falla con ORA-30673 porque esa sintaxis solo cambia las opciones de una
-- columna que YA es identidad. Hay que reemplazar la columna. La tabla
-- esta vacia, asi que no se pierde nada.
-- Efecto secundario: ID queda como ultima columna en vez de primera. Es
-- solo cosmetico — JPA mapea por nombre y los scripts listan las columnas
-- explicitamente, nada depende del orden fisico.

ALTER TABLE PGS.DRC2 DROP COLUMN ID;

ALTER TABLE PGS.DRC2 ADD ID NUMBER GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE PGS.DRC2 ADD CONSTRAINT PK_DRC2 PRIMARY KEY (ID);

ALTER TABLE PGS.DRC2 MODIFY RETENCIONV2 NOT NULL;

ALTER TABLE PGS.DRC2 ADD CONSTRAINT FK_DRC2_RETENCION FOREIGN KEY (RETENCIONV2) REFERENCES PGS.RCV2 (ID);

CREATE INDEX IDX_DRC2_RETENCION ON PGS.DRC2 (RETENCIONV2);

CREATE INDEX IDX_DRC2_NUMDOCRETEN ON PGS.DRC2 (NUMDOCRETEN);

COMMENT ON TABLE PGS.DRC2 IS 'Detalle de retenciones v2 recibidas de clientes. Cada fila es un impuesto retenido; NUMDOCRETEN identifica la factura de venta a la que abona.';

COMMENT ON COLUMN PGS.DRC2.NUMDOCRETEN IS 'Numero del documento sustento (la factura de venta que esta retencion abona). Sin este dato no se puede registrar el cobro sobre la factura.';


