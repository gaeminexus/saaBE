-- BLOQUE 0 — CONTROL ANTES. ESPERADO: 0 filas en las dos.
SELECT OWNER, TABLE_NAME FROM ALL_TABLES WHERE TABLE_NAME = 'GRPR';
SELECT SEQUENCE_OWNER, SEQUENCE_NAME FROM ALL_SEQUENCES WHERE SEQUENCE_NAME = 'SQ_GRPRCDGO';


-- BLOQUE 1 — TABLA
CREATE TABLE CRD.GRPR (
    GRPRCDGO NUMBER            NOT NULL,
    PRSTCDGO NUMBER            NOT NULL,
    ENTDCDGO NUMBER,
    GRPRNMBR VARCHAR2(200)     NOT NULL,
    GRPRNMID VARCHAR2(20)      NOT NULL,
    GRPRDRCC VARCHAR2(500),
    GRPRTLFN VARCHAR2(50),
    GRPRCRRE VARCHAR2(100),
    GRPRESTD NUMBER  DEFAULT 1 NOT NULL,
    GRPRUSRG VARCHAR2(50)      NOT NULL,
    GRPRFCRG TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    GRPRUSMD VARCHAR2(50),
    GRPRFCMD TIMESTAMP
);

ALTER TABLE CRD.GRPR ADD CONSTRAINT PK_GRPR PRIMARY KEY (GRPRCDGO);
CREATE SEQUENCE CRD.SQ_GRPRCDGO START WITH 1 INCREMENT BY 1 NOCACHE;

ALTER TABLE CRD.GRPR ADD CONSTRAINT FK_GRPR_PRST FOREIGN KEY (PRSTCDGO) REFERENCES CRD.PRST (PRSTCDGO);
ALTER TABLE CRD.GRPR ADD CONSTRAINT FK_GRPR_ENTD FOREIGN KEY (ENTDCDGO) REFERENCES CRD.ENTD (ENTDCDGO);
ALTER TABLE CRD.GRPR ADD CONSTRAINT CK_GRPR_ESTADO CHECK (GRPRESTD IN (0, 1));

-- Un solo garante ACTIVO por préstamo; los anulados (0) no cuentan.
CREATE UNIQUE INDEX CRD.UX_GRPR_PRESTAMO ON CRD.GRPR (CASE WHEN GRPRESTD = 1 THEN PRSTCDGO END);
CREATE INDEX CRD.IDX_GRPR_PRST ON CRD.GRPR (PRSTCDGO);

COMMENT ON TABLE  CRD.GRPR IS 'Garante del prestamo: firma el pagare junto con el titular (sql/369)';
COMMENT ON COLUMN CRD.GRPR.PRSTCDGO IS 'Prestamo garantizado (CRD.PRST)';
COMMENT ON COLUMN CRD.GRPR.ENTDCDGO IS 'Entidad del garante si es participe; nulo si es un tercero';
COMMENT ON COLUMN CRD.GRPR.GRPRNMBR IS 'Apellidos y nombres del garante';
COMMENT ON COLUMN CRD.GRPR.GRPRNMID IS 'Cedula del garante';
COMMENT ON COLUMN CRD.GRPR.GRPRDRCC IS 'Direccion del garante';
COMMENT ON COLUMN CRD.GRPR.GRPRTLFN IS 'Telefono del garante';
COMMENT ON COLUMN CRD.GRPR.GRPRCRRE IS 'Correo del garante';
COMMENT ON COLUMN CRD.GRPR.GRPRESTD IS '1 activo, 0 anulado';


-- BLOQUE 2 — CONTROL DESPUÉS
-- 2.1 PK, 2 FK y 1 CHECK habilitados.
SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CRD' AND TABLE_NAME = 'GRPR' AND CONSTRAINT_NAME NOT LIKE 'SYS_%' ORDER BY 1;
-- 2.2 Índices (PK + 2) y secuencia (1).
SELECT INDEX_NAME, UNIQUENESS FROM ALL_INDEXES WHERE OWNER = 'CRD' AND TABLE_NAME = 'GRPR' ORDER BY 1;
SELECT SEQUENCE_NAME, LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'CRD' AND SEQUENCE_NAME = 'SQ_GRPRCDGO';


