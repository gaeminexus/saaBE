-- ⛔ POR QUE ESTA TABLA EXISTE, y por que se escribe donde se escribe:
--
--   Hoy la clasificacion en bandas vive en un Map EN MEMORIA dentro de la contabilizacion
--   (CobroPetroContableServiceImpl:720) y muere cuando el metodo termina. Nadie la persiste.
--   Eso tiene dos consecuencias:
--     1. Contabilidad no puede auditar nada: el dato no existe despues del asiento.
--     2. Si contabilidadActiva() esta en false, NO SE CLASIFICA NADA. El dia que se
--        desconecte contabilidad para vender el sistema aparte, una pantalla alimentada
--        desde la contabilizacion queda VACIA.
--
--   Por eso la fila se escribe DONDE SE APLICA EL PAGO, no donde se arma el asiento.
--   La banda no es un dato contable: es un dato de CARTERA. "esta cuota vence en 45 dias"
--   es verdad exista o no un asiento detras. Contabilidad CONSUME esa clasificacion.
--
-- ⛔ POR ESO ASNTCDGO ES NULLABLE, y no es un descuido: es EL enganche con contabilidad,
--    y el unico. Con CNT conectado se llena; desconectado queda null y no pasa nada mas.
--    LA CUENTA CONTABLE NO SE GUARDA: se resuelve al consultar, uniendo con la
--    configuracion de bandas. Sin CNT la pantalla pierde UNA COLUMNA, no la funcion.
--
--   En cambio DSBNETQT (la etiqueta de la banda) SI se guarda, y la diferencia importa:
--   la etiqueta la deriva CRD desde su propia parametrizacion, y una reconfiguracion
--   posterior de las bandas NO debe reescribir la historia de lo que ya se distribuyo.
--   Una tabla de auditoria guarda lo que valia EN SU MOMENTO.
--
-- ⛔ ORIGEN + IDORIGEN, no "idCarga": la carga Petro es UN origen, no la estructura.
--    Clasifican por bandas tambien el cobro individual, el abono a capital y la
--    precancelacion. Colgar la tabla de la carga cuesta lo mismo hoy y obliga a rehacer
--    tabla y pantalla la primera vez que contabilidad pregunte por un cobro individual.
--
-- ESTANDAR: docs/estandar/ESTANDARES-CREACION-TABLAS-ORACLE.md
-- =====================================================================================

