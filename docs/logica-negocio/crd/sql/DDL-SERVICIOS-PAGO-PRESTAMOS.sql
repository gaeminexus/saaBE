-- =====================================================================================
-- 7. CONTROLES POSTERIORES A LA EJECUCIÓN
-- =====================================================================================

-- 7.1 Las dos tablas nuevas existen y están vacías
SELECT 'EVPR' AS TABLA, COUNT(*) AS FILAS FROM CRD.EVPR
UNION ALL
SELECT 'HDTP', COUNT(*) FROM CRD.HDTP;

-- 7.2 Las columnas nuevas de PGPR y PGAP existen
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, NULLABLE, DATA_DEFAULT
FROM   ALL_TAB_COLUMNS
WHERE  OWNER = 'CRD'
AND   (   (TABLE_NAME = 'PGPR' AND COLUMN_NAME IN ('EVPRCDGO','PGPRASNT','PGPRANUL','PGPRUSAN','PGPRFCAN','PGPRMTAN'))
       OR (TABLE_NAME = 'PGAP' AND COLUMN_NAME = 'PGPRCDGO'))
ORDER BY TABLE_NAME, COLUMN_NAME;

-- 7.3 El espejo HDTP tiene exactamente las mismas columnas DTPR* que DTPR (debe devolver 0 filas)
SELECT COLUMN_NAME, 'FALTA EN HDTP' AS PROBLEMA
FROM   ALL_TAB_COLUMNS
WHERE  OWNER = 'CRD' AND TABLE_NAME = 'DTPR'
AND    COLUMN_NAME NOT IN (SELECT COLUMN_NAME FROM ALL_TAB_COLUMNS WHERE OWNER = 'CRD' AND TABLE_NAME = 'HDTP');

-- 7.4 Índices creados
SELECT INDEX_NAME, TABLE_NAME, STATUS
FROM   ALL_INDEXES
WHERE  OWNER = 'CRD'
AND    INDEX_NAME IN ('IDX_EVPR_PRST','IDX_HDTP_PRST','IDX_HDTP_EVPR','IDX_PGPR_EVPR',
                      'IDX_PGAP_PGPR','IDX_APRT_ENTD_TPAP','IDX_APRT_ENTD_TPAP_SLDO')
ORDER BY TABLE_NAME, INDEX_NAME;

-- 7.5 Ningún pago quedó con la marca de anulación en NULL (debe devolver 0)
SELECT COUNT(*) AS PAGOS_CON_ANUL_NULO FROM CRD.PGPR WHERE PGPRANUL IS NULL;
