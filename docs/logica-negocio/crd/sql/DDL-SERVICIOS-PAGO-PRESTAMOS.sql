-- =====================================================================================
-- 3. ALTER CRD.PGPR (PagoPrestamo): evento + asiento + anulación
-- =====================================================================================

ALTER TABLE CRD.PGPR ADD (
    EVPRCDGO NUMBER,                 -- FK evento; NULL en pagos petro/migración existentes
    PGPRASNT NUMBER,                 -- código de asiento contable (hook futuro)
    PGPRANUL NUMBER DEFAULT 0,       -- 0 = vigente, 1 = anulado
    PGPRUSAN VARCHAR2(50),
    PGPRFCAN TIMESTAMP,
    PGPRMTAN VARCHAR2(500)
);

ALTER TABLE CRD.PGPR ADD CONSTRAINT FK_PGPR_EVPR FOREIGN KEY (EVPRCDGO) REFERENCES CRD.EVPR(EVPRCDGO);

CREATE INDEX IDX_PGPR_EVPR ON CRD.PGPR(EVPRCDGO);

COMMENT ON COLUMN CRD.PGPR.EVPRCDGO IS 'FK CRD.EVPR - Evento de pago que generó este registro. NULL en los pagos históricos (petro / migración) anteriores a los servicios de pago';
COMMENT ON COLUMN CRD.PGPR.PGPRASNT IS 'Código del asiento contable asociado al pago (hook futuro; NULL por ahora)';
COMMENT ON COLUMN CRD.PGPR.PGPRANUL IS 'Marca de anulación: 0 = vigente, 1 = anulado. Los pagos anulados NO cuentan en la reconstrucción de saldos de la cuota';
COMMENT ON COLUMN CRD.PGPR.PGPRUSAN IS 'Usuario que anuló el pago';
COMMENT ON COLUMN CRD.PGPR.PGPRFCAN IS 'Fecha/hora de anulación del pago';
COMMENT ON COLUMN CRD.PGPR.PGPRMTAN IS 'Motivo de la anulación del pago';

-- Los pagos preexistentes quedan explícitamente vigentes (el DEFAULT 0 solo aplica a filas nuevas).
UPDATE CRD.PGPR SET PGPRANUL = 0 WHERE PGPRANUL IS NULL;
COMMIT;


