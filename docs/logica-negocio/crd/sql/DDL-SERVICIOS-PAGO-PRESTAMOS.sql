-- =====================================================================================
-- 1. TABLA: CRD.EVPR (EventoPrestamo)
-- DESCRIPCIÓN: Cabecera de toda operación de pago sobre un préstamo. Cada llamada de
--              negocio (pago manual, pago con aportes, abono a capital, precancelación)
--              crea UN EventoPrestamo; los PagoPrestamo, movimientos de aportes y cuotas
--              historizadas de esa llamada cuelgan del evento. Es el punto de agrupación
--              para el reverso y para el asiento contable.
-- =====================================================================================

CREATE TABLE CRD.EVPR (
    -- PK Autoincrementable (Oracle 12c+)
    EVPRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    -- FK al préstamo afectado
    PRSTCDGO NUMBER NOT NULL,

    -- DATOS DE LA OPERACIÓN
    EVPRTPOO VARCHAR2(30) NOT NULL,            -- PAGO_MANUAL | PAGO_APORTES | ABONO_CAPITAL | PRECANCELACION
    EVPRVLRR NUMBER(18,2) NOT NULL,            -- valor total de la operación
    EVPRMDLD NUMBER,                           -- abono: 1=reduce plazo, 2=reduce cuota. NULL en otros tipos
    EVPRPLZA NUMBER,                           -- plazo anterior (abono modalidad 1)
    EVPRPLZN NUMBER,                           -- plazo nuevo
    EVPRCTAA NUMBER(18,2),                     -- valor cuota anterior (abono modalidad 2)
    EVPRCTNN NUMBER(18,2),                     -- valor cuota nuevo
    EVPRFCHA DATE NOT NULL,                    -- fecha de negocio de la operación
    EVPRNMAS NUMBER,                           -- número de asiento contable (hook futuro; NULL por ahora)
    EVPROBSR VARCHAR2(2000),                   -- observación del usuario

    -- AUDITORÍA
    EVPRUSAR VARCHAR2(50) NOT NULL,            -- usuario que ejecutó
    EVPRFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    -- ESTADO Y ANULACIÓN
    EVPRESTD NUMBER DEFAULT 1 NOT NULL,        -- 1 = vigente, 0 = anulado
    EVPRUSAN VARCHAR2(50),                     -- usuario anulación
    EVPRFCAN TIMESTAMP,                        -- fecha anulación
    EVPRMTAN VARCHAR2(500),                    -- motivo anulación

    -- CONSTRAINTS
    CONSTRAINT PK_EVPR PRIMARY KEY (EVPRCDGO),
    CONSTRAINT FK_EVPR_PRST FOREIGN KEY (PRSTCDGO) REFERENCES CRD.PRST(PRSTCDGO),
    CONSTRAINT CK_EVPR_TIPO CHECK (EVPRTPOO IN ('PAGO_MANUAL','PAGO_APORTES','ABONO_CAPITAL','PRECANCELACION'))
);

CREATE INDEX IDX_EVPR_PRST ON CRD.EVPR(PRSTCDGO);

COMMENT ON TABLE  CRD.EVPR           IS 'EventoPrestamo: cabecera de toda operación de pago de préstamo (pago manual, pago con aportes, abono a capital, precancelación). Agrupa los PGPR, movimientos de aporte y cuotas historizadas de la operación.';
COMMENT ON COLUMN CRD.EVPR.EVPRCDGO  IS 'Código del evento (PK)';
COMMENT ON COLUMN CRD.EVPR.PRSTCDGO  IS 'FK CRD.PRST - Préstamo afectado por la operación';
COMMENT ON COLUMN CRD.EVPR.EVPRTPOO  IS 'Tipo de operación: PAGO_MANUAL, PAGO_APORTES, ABONO_CAPITAL o PRECANCELACION';
COMMENT ON COLUMN CRD.EVPR.EVPRVLRR  IS 'Valor total de la operación';
COMMENT ON COLUMN CRD.EVPR.EVPRMDLD  IS 'Modalidad del abono a capital: 1 = mantiene cuota y reduce plazo, 2 = mantiene plazo y reduce cuota. NULL en los demás tipos';
COMMENT ON COLUMN CRD.EVPR.EVPRPLZA  IS 'Plazo del préstamo ANTES de la operación (abono a capital)';
COMMENT ON COLUMN CRD.EVPR.EVPRPLZN  IS 'Plazo del préstamo DESPUÉS de la operación (abono a capital)';
COMMENT ON COLUMN CRD.EVPR.EVPRCTAA  IS 'Valor de cuota ANTES de la operación (abono a capital)';
COMMENT ON COLUMN CRD.EVPR.EVPRCTNN  IS 'Valor de cuota DESPUÉS de la operación (abono a capital)';
COMMENT ON COLUMN CRD.EVPR.EVPRFCHA  IS 'Fecha de negocio de la operación (la que informa el usuario, no la de registro)';
COMMENT ON COLUMN CRD.EVPR.EVPRNMAS  IS 'Número de asiento contable generado por el hook de contabilidad. NULL mientras la contabilidad de préstamos no esté activa';
COMMENT ON COLUMN CRD.EVPR.EVPROBSR  IS 'Observación registrada por el usuario';
COMMENT ON COLUMN CRD.EVPR.EVPRUSAR  IS 'Usuario que ejecutó la operación';
COMMENT ON COLUMN CRD.EVPR.EVPRFCRG  IS 'Fecha/hora de registro del evento';
COMMENT ON COLUMN CRD.EVPR.EVPRESTD  IS 'Estado del evento: 1 = vigente, 0 = anulado';
COMMENT ON COLUMN CRD.EVPR.EVPRUSAN  IS 'Usuario que anuló el evento';
COMMENT ON COLUMN CRD.EVPR.EVPRFCAN  IS 'Fecha/hora de anulación del evento';
COMMENT ON COLUMN CRD.EVPR.EVPRMTAN  IS 'Motivo de la anulación';


-- =====================================================================================
-- 2. TABLA: CRD.HDTP (HistDetallePrestamo)
-- DESCRIPCIÓN: Cuotas historizadas. Cuando un abono a capital (o una precancelación con
--              re-amortización) reemplaza cuotas de CRD.DTPR, esas cuotas se copian aquí
--              y se BORRAN de DTPR en la misma transacción. Prohibido dejarlas en DTPR con
--              un estado nuevo: rompería contarCuotasPendientesByPrestamo y los reportes.
--              Mismo patrón que MayorizacionServiceImpl.respaldaAsientosMayorizacion / CNT.ASNH.
--
-- ESPEJO: las columnas DTPR* de abajo son un espejo 1:1 (mismo nombre y tipo) de CRD.DTPR.
--         Verificado contra com.saa.model.crd.DetallePrestamo el 2026-08-13:
--         37 columnas de datos + PRSTCDGO. No hay ningún campo de la entidad fuera del espejo.
-- =====================================================================================

CREATE TABLE CRD.HDTP (
    -- PK Autoincrementable (Oracle 12c+)
    HDTPCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,

    -- IDENTIFICACIÓN DEL ORIGEN
    DTPRCDGO NUMBER NOT NULL,        -- código que tenía la cuota en DTPR (sin FK: la fila viva se borra)
    EVPRCDGO NUMBER NOT NULL,        -- FK CRD.EVPR: evento que la historizó
    HDTPMTVO VARCHAR2(30) NOT NULL,  -- ABONO_CAPITAL | PRECANCELACION | REVERSO

    -- AUDITORÍA
    HDTPFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    HDTPUSAR VARCHAR2(50) NOT NULL,

    -- ================= ESPEJO 1:1 DE CRD.DTPR =================
    PRSTCDGO NUMBER NOT NULL,
    DTPRNMCT NUMBER,
    DTPRFCVN DATE,
    DTPRCPTL NUMBER(18,2),
    DTPRINTR NUMBER(18,2),
    DTPRMRAA NUMBER(18,2),
    DTPRINVN NUMBER(18,2),
    DTPRSLCP NUMBER(18,2),
    DTPRSLIN NUMBER(18,2),
    DTPRSLMR NUMBER(18,2),
    DTPRSLIV NUMBER(18,2),
    DTPRFCPG DATE,
    DTPRABNO NUMBER(18,2),
    DTPRCPPG NUMBER(18,2),
    DTPRINPG NUMBER(18,2),
    DTPRDSGR NUMBER(18,2),
    DTPRCTAA NUMBER(18,2),
    DTPRSLDO NUMBER(18,2),
    DTPRSLOT NUMBER(18,2),
    DTPRDSFR NUMBER(18,2),
    DTPRDSDF NUMBER(18,2),
    DTPRDSOR NUMBER(18,2),
    DTPRVLDF NUMBER(18,2),
    DTPRTTLL NUMBER(18,2),
    DTPRMRPG NUMBER(18,2),
    DTPRDSPG NUMBER(18,2),
    DTPRINVP NUMBER(18,2),
    DTPRMRCL NUMBER(18,2),
    DTPRDSMR NUMBER,
    DTPRESTD NUMBER,
    DTPRFCRG DATE,
    DTPRUSRG VARCHAR2(200),
    DTPRIDST NUMBER,
    DTPRCDEX NUMBER,
    DTPROTSG NUMBER(18,2),
    DTPRTTCS NUMBER(18,2),
    DTPRVLSI NUMBER(18,2),
    DTPRSICP NUMBER(18,2),

    -- CONSTRAINTS
    CONSTRAINT PK_HDTP PRIMARY KEY (HDTPCDGO),
    CONSTRAINT FK_HDTP_EVPR FOREIGN KEY (EVPRCDGO) REFERENCES CRD.EVPR(EVPRCDGO)
);

CREATE INDEX IDX_HDTP_PRST ON CRD.HDTP(PRSTCDGO);
CREATE INDEX IDX_HDTP_EVPR ON CRD.HDTP(EVPRCDGO);

COMMENT ON TABLE  CRD.HDTP           IS 'HistDetallePrestamo: cuotas de CRD.DTPR historizadas al re-amortizar (abono a capital / precancelación). Espejo 1:1 de DTPR con los mismos nombres de columna, más el evento que las historizó.';
