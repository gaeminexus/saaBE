-- BLOQUE 2 — TABLAS
CREATE SEQUENCE CRD.SQ_FRCNCDGO START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE CRD.SQ_FRFRCDGO START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE CRD.FRCN (
    FRCNCDGO  NUMBER          NOT NULL,
    CNTRCDGO  NUMBER          NOT NULL,
    FRCNPRVD  VARCHAR2(30)    NOT NULL,
    FRCNIDEX  VARCHAR2(200),
    FRCNESTD  NUMBER(2)       NOT NULL,
    FRCNADOR  NUMBER,
    FRCNADFR  NUMBER,
    FRCNHASH  VARCHAR2(64),
    FRCNFCEN  TIMESTAMP,
    FRCNFCFR  TIMESTAMP,
    FRCNFCUC  TIMESTAMP,
    FRCNERRR  VARCHAR2(2000),
    FRCNFCRG  TIMESTAMP       NOT NULL,
    FRCNUSRG  VARCHAR2(50)    NOT NULL,
    FRCNFCAN  TIMESTAMP,
    FRCNUSAN  VARCHAR2(50),
    FRCNMTAN  VARCHAR2(500),
    CONSTRAINT PK_FRCN PRIMARY KEY (FRCNCDGO),
    CONSTRAINT FK_FRCN_CNTR FOREIGN KEY (CNTRCDGO) REFERENCES CRD.CNTR (CNTRCDGO),
    CONSTRAINT FK_FRCN_ADOR FOREIGN KEY (FRCNADOR) REFERENCES CRD.ADJN (ADJNCDGO),
    CONSTRAINT FK_FRCN_ADFR FOREIGN KEY (FRCNADFR) REFERENCES CRD.ADJN (ADJNCDGO),
    CONSTRAINT CK_FRCN_ESTD CHECK (FRCNESTD IN (1, 2, 3, 4, 5, 6))
);
CREATE INDEX IX_FRCN_CNTR ON CRD.FRCN (CNTRCDGO);
-- Un solo trámite vivo (1 PENDIENTE_ENVIO / 2 ENVIADO) por contrato.
CREATE UNIQUE INDEX UX_FRCN_VIVO ON CRD.FRCN (CASE WHEN FRCNESTD IN (1, 2) THEN CNTRCDGO END);

COMMENT ON TABLE  CRD.FRCN IS 'Tramite de firma electronica del contrato de adhesion (sql/376)';
COMMENT ON COLUMN CRD.FRCN.FRCNPRVD IS 'Proveedor de firma (SECURITY_DATA)';
COMMENT ON COLUMN CRD.FRCN.FRCNIDEX IS 'Identificador del tramite en el proveedor';
COMMENT ON COLUMN CRD.FRCN.FRCNESTD IS '1 PENDIENTE_ENVIO, 2 ENVIADO, 3 FIRMADO, 4 RECHAZADO, 5 VENCIDO, 6 ANULADO';
COMMENT ON COLUMN CRD.FRCN.FRCNADOR IS 'Adjunto (CRD.ADJN) con el PDF original enviado';
COMMENT ON COLUMN CRD.FRCN.FRCNADFR IS 'Adjunto (CRD.ADJN) con el PDF firmado';
COMMENT ON COLUMN CRD.FRCN.FRCNHASH IS 'SHA-256 del PDF enviado';

CREATE TABLE CRD.FRFR (
    FRFRCDGO  NUMBER          NOT NULL,
    FRCNCDGO  NUMBER          NOT NULL,
    FRFRORDN  NUMBER(2)       NOT NULL,
    FRFRROLL  VARCHAR2(30)    NOT NULL,
    FRFRIDNT  VARCHAR2(50)    NOT NULL,
    FRFRNMBR  VARCHAR2(300)   NOT NULL,
    FRFRCRRO  VARCHAR2(200),
    FRFRCLLR  VARCHAR2(50),
    ENTDCDGO  NUMBER,
    FRFRESTD  NUMBER(2)       NOT NULL,
    FRFRFCFR  TIMESTAMP,
    FRFRIDEX  VARCHAR2(200),
    CONSTRAINT PK_FRFR PRIMARY KEY (FRFRCDGO),
    CONSTRAINT FK_FRFR_FRCN FOREIGN KEY (FRCNCDGO) REFERENCES CRD.FRCN (FRCNCDGO),
    CONSTRAINT FK_FRFR_ENTD FOREIGN KEY (ENTDCDGO) REFERENCES CRD.ENTD (ENTDCDGO),
    CONSTRAINT CK_FRFR_ESTD CHECK (FRFRESTD IN (1, 2, 3)),
    CONSTRAINT CK_FRFR_ROLL CHECK (FRFRROLL IN ('PARTICIPE', 'REPRESENTANTE_ASOPREP')),
    CONSTRAINT UX_FRFR_ORDN UNIQUE (FRCNCDGO, FRFRORDN)
);

COMMENT ON TABLE  CRD.FRFR IS 'Firmantes del tramite de firma del contrato (sql/376); datos copiados al enviar';
COMMENT ON COLUMN CRD.FRFR.FRFRESTD IS '1 PENDIENTE, 2 FIRMADO, 3 RECHAZADO';

-- BLOQUE 3 — TIPOS DE ADJUNTO (el código los resuelve por nombre exacto y activo, como el certificado bancario)
INSERT INTO CRD.TPDJ (TPDJNMBR, TPDJIDST)
SELECT 'CONTRATO DE ADHESION', 1 FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM CRD.TPDJ t WHERE UPPER(TRIM(t.TPDJNMBR)) = 'CONTRATO DE ADHESION');
INSERT INTO CRD.TPDJ (TPDJNMBR, TPDJIDST)
SELECT 'CONTRATO DE ADHESION FIRMADO', 1 FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM CRD.TPDJ t WHERE UPPER(TRIM(t.TPDJNMBR)) = 'CONTRATO DE ADHESION FIRMADO');
COMMIT;

