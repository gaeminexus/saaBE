-- C14b (2026-10-29), solo lectura. Cortes fin de mes may-2025 .. oct-2026: cuotas del universo al corte cuyo
-- capital pendiente cambia con la regla nueva (el pago ABONO_CAPITAL solo descuenta PGPRCPPG de su cuota).
-- Resultado esperado al 29-oct-2026: solo 8052 #42, pendiente 0 -> 445,72, desde jun-2025.
-- Ver CIERRE-CARTERA-A-FECHA-DE-CORTE.md §1.1.1.
WITH C AS (SELECT LAST_DAY(ADD_MONTHS(DATE '2025-05-01', LEVEL - 1)) CORTE FROM DUAL CONNECT BY LEVEL <= 18),
G AS (SELECT C.CORTE, g.DTPRCDGO,
             SUM(CASE WHEN NVL(g.PGPRSLOT,0) > 0 THEN g.PGPRSLOT ELSE NVL(g.PGPRCPPG,0) END) CAP_VIEJO,
             SUM(CASE WHEN g.PGPRTPOO = 'ABONO_CAPITAL' THEN NVL(g.PGPRCPPG,0)
                      WHEN NVL(g.PGPRSLOT,0) > 0 THEN g.PGPRSLOT ELSE NVL(g.PGPRCPPG,0) END) CAP_NUEVO
      FROM CRD.PGPR g, C WHERE NVL(g.PGPRANUL,0) = 0 AND g.PGPRFCHA < C.CORTE + 1 GROUP BY C.CORTE, g.DTPRCDGO)
SELECT G.CORTE, p.PRSTCDGO, d.DTPRNMCT, d.DTPRCPTL,
       ROUND(GREATEST(NVL(d.DTPRCPTL,0) - NVL(G.CAP_VIEJO,0), 0),2) PEND_VIEJO,
       ROUND(GREATEST(NVL(d.DTPRCPTL,0) - NVL(G.CAP_NUEVO,0), 0),2) PEND_NUEVO
FROM CRD.DTPR d JOIN CRD.PRST p ON p.PRSTCDGO = d.PRSTCDGO JOIN G ON G.DTPRCDGO = d.DTPRCDGO
WHERE p.PRSTFCHA < G.CORTE + 1 AND NVL(p.PRSTIDST,0) NOT IN (0,1,6,7,12)
  AND NOT (NVL(d.DTPRESTD,0) IN (4,7) AND NVL(d.DTPRFCPG, G.CORTE + 1) < G.CORTE + 1)
  AND ROUND(GREATEST(NVL(d.DTPRCPTL,0) - NVL(G.CAP_VIEJO,0), 0),2) <> ROUND(GREATEST(NVL(d.DTPRCPTL,0) - NVL(G.CAP_NUEVO,0), 0),2)
ORDER BY 1, 2, 3
