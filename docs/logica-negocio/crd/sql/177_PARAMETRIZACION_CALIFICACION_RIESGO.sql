-- =====================================================================================
-- CONTROL DESPUES — ⛔ SI ESTO NO DA LO ESPERADO, EL DESPLIEGUE NO VA
-- =====================================================================================

-- D.1 — Una configuracion por producto, y 9 calificaciones cada una.
--       CALIFICACIONES debe dar 9 en TODAS las filas. Si alguna da menos, un INSERT fallo.
SELECT c.CFCRCDGO, c.PRDCCDGO, c.CFCRNMBR, COUNT(e.ESCRCDGO) AS CALIFICACIONES
FROM   CRD.CFCR c
LEFT   JOIN CRD.ESCR e ON e.CFCRCDGO = c.CFCRCDGO
GROUP  BY c.CFCRCDGO, c.PRDCCDGO, c.CFCRNMBR
ORDER  BY c.CFCRNMBR, c.PRDCCDGO;

-- D.2 — Las dos escalas, una vez cada una, para comparar VALOR POR VALOR contra la tabla
--       del §2 del plan. Es la verificacion que importa: si un rango o un porcentaje
--       difiere de lo cableado, el G48 va a cambiar de resultado y eso es un ERROR.
SELECT DISTINCT c.CFCRNMBR AS ESCALA, e.ESCRORDN AS ORDEN, e.ESCRCLFC AS CALIFICACION,
       e.ESCRDSDE AS DIA_DESDE, e.ESCRHSTA AS DIA_HASTA, e.ESCRPRVS AS PROVISION
FROM   CRD.ESCR e
JOIN   CRD.CFCR c ON c.CFCRCDGO = e.CFCRCDGO
ORDER  BY ESCALA, ORDEN;

-- D.3 — ⛔ Huecos y solapes. Debe salir 0 filas.
--       Cada calificacion tiene que empezar justo donde termino la anterior. Un hueco deja
--       creditos sin calificar; un solape los califica dos veces.
SELECT c.CFCRNMBR AS ESCALA, e.ESCRCLFC AS CALIFICACION, e.ESCRDSDE, e.ESCRHSTA,
       LAG(e.ESCRHSTA) OVER (PARTITION BY e.CFCRCDGO ORDER BY e.ESCRORDN) AS HASTA_ANTERIOR,
       'HUECO O SOLAPE' AS PROBLEMA
FROM   CRD.ESCR e
JOIN   CRD.CFCR c ON c.CFCRCDGO = e.CFCRCDGO
WHERE  e.ESCRDSDE <> NVL(LAG(e.ESCRHSTA) OVER (PARTITION BY e.CFCRCDGO ORDER BY e.ESCRORDN), -1) + 1;

-- D.4 — Productos SIN configuracion. Debe salir 0 filas.
--       Cada fila es un producto cuyo G48 va a fallar (o a calificarse mal) tras el cambio.
SELECT p.PRDCCDGO, p.PRDCNMBR, 'SIN CONFIGURACION DE CALIFICACION' AS PROBLEMA
FROM   CRD.PRDC p
WHERE  NOT EXISTS (SELECT 1 FROM CRD.CFCR c WHERE c.PRDCCDGO = p.PRDCCDGO);


