-- A.1 — Las tablas NO deben existir. Debe salir 0 filas.
SELECT t.TABLE_NAME FROM ALL_TABLES t
WHERE  t.OWNER = 'CRD' AND t.TABLE_NAME IN ('CFCR', 'ESCR');

-- A.2 — ⛔ Los productos que HOY se califican como hipotecarios (literal 7, 8, 21 en el
--       codigo). Deben salir 3 filas. Si alguno no existe o cambio de nombre, PARAR:
--       el literal del codigo ya estaba desactualizado y hay que revisarlo con el usuario
--       antes de congelarlo en la parametrizacion.
SELECT p.PRDCCDGO, p.PRDCNMBR, p.PRDCCDEX
FROM   CRD.PRDC p
WHERE  p.PRDCCDGO IN (7, 8, 21)
ORDER  BY p.PRDCCDGO;

-- A.3 — ⛔ TODOS los productos de credito. Los que NO esten en (7,8,21) van a quedar con
--       escala GENERAL. Revisar la lista con el usuario ANTES de correr los INSERT:
--       si hay un producto hipotecario que no esta en el literal, HOY se esta calificando
--       mal y este script congelaria el error.
SELECT p.PRDCCDGO, p.PRDCNMBR,
       CASE WHEN p.PRDCCDGO IN (7,8,21) THEN 'HIPOTECARIA' ELSE 'GENERAL' END AS ESCALA_QUE_LE_TOCA
FROM   CRD.PRDC p
ORDER  BY ESCALA_QUE_LE_TOCA, p.PRDCCDGO;


-- =====================================================================================
-- EJECUCION — LAS TABLAS
-- =====================================================================================

CREATE TABLE CRD.CFCR (
    CFCRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    PRDCCDGO NUMBER        NOT NULL,   -- producto al que aplica
    PJRQCDGO NUMBER,                   -- empresa (jerarquia), como en CBPR
    CFCRNMBR VARCHAR2(100),            -- nombre de la escala, p.ej. 'HIPOTECARIA' / 'GENERAL'
    CFCRFCIN DATE          NOT NULL,   -- vigencia desde
    CFCRFCFN DATE,                     -- vigencia hasta (null = abierta)
    CFCRFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CFCRUSAR VARCHAR2(50),
    CFCRESTD NUMBER DEFAULT 1,
    CONSTRAINT PK_CFCR PRIMARY KEY (CFCRCDGO),
    CONSTRAINT FK_CFCR_PRDC FOREIGN KEY (PRDCCDGO) REFERENCES CRD.PRDC(PRDCCDGO)
);

CREATE TABLE CRD.ESCR (
    ESCRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    CFCRCDGO NUMBER        NOT NULL,   -- configuracion a la que pertenece
    ESCRCLFC VARCHAR2(5)   NOT NULL,   -- A1, A2, A3, B1, B2, C1, C2, D, E
    ESCRDSDE NUMBER        NOT NULL,   -- dia desde (inclusive)
    ESCRHSTA NUMBER,                   -- dia hasta (inclusive). NULL = sin tope (la ultima)
    ESCRPRVS NUMBER(18,6)  NOT NULL,   -- porcentaje de provision, en tanto por uno (0.0099 = 0,99%)
    ESCRORDN NUMBER,                   -- orden de evaluacion
    ESCRFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ESCRUSAR VARCHAR2(50),
    ESCRESTD NUMBER DEFAULT 1,
    CONSTRAINT PK_ESCR PRIMARY KEY (ESCRCDGO),
    CONSTRAINT FK_ESCR_CFCR FOREIGN KEY (CFCRCDGO) REFERENCES CRD.CFCR(CFCRCDGO)
);

CREATE INDEX IDX_CFCR_PRODUCTO ON CRD.CFCR(PRDCCDGO);
CREATE INDEX IDX_ESCR_CONFIG   ON CRD.ESCR(CFCRCDGO);

COMMENT ON TABLE  CRD.CFCR IS 'Configuracion de calificacion de riesgo por producto y vigencia. DISTINTA de las bandas contables (CBPR/BNDP): la banda dice a que cuenta va el saldo, la calificacion dice cuanta provision se constituye.';
COMMENT ON TABLE  CRD.ESCR IS 'Escala de calificacion de riesgo: rango de dias y porcentaje de provision por calificacion (A1..E).';
COMMENT ON COLUMN CRD.ESCR.ESCRPRVS IS 'Porcentaje de provision en TANTO POR UNO (0.0099 = 0,99%), igual que el codigo cableado que reemplaza.';
COMMENT ON COLUMN CRD.ESCR.ESCRHSTA IS 'Dia hasta inclusive. NULL en la ultima calificacion de la escala (sin tope superior).';

COMMIT;


-- =====================================================================================
