COMMIT;

-- Detalle HIPOTECARIA (productos 7, 8, 21)
INSERT INTO CRD.ESCR (CFCRCDGO, ESCRCLFC, ESCRDSDE, ESCRHSTA, ESCRPRVS, ESCRORDN, ESCRUSAR, ESCRESTD)
SELECT c.CFCRCDGO, e.CLFC, e.DSDE, e.HSTA, e.PRVS, e.ORDN, 'sql/177', 1
