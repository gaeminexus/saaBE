SELECT c.CFCRCDGO, e.CLFC, e.DSDE, e.HSTA, e.PRVS, e.ORDN, 'sql/177', 1
FROM   CRD.CFCR c
CROSS  JOIN (
    SELECT 'A1' CLFC,   0 DSDE,    0 HSTA, 0.0099 PRVS, 1 ORDN FROM DUAL UNION ALL
    SELECT 'A2',        1,        15,      0.0199,      2      FROM DUAL UNION ALL
