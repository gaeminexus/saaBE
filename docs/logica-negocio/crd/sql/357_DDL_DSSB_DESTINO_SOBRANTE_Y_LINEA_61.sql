-- BLOQUE 0 — CONTROL ANTES. ESPERADO: 0 filas en las dos.
SELECT OWNER, TABLE_NAME FROM ALL_TABLES WHERE TABLE_NAME = 'DSSB';
SELECT d.DTPLCDGO FROM CNT.PLNS p JOIN CNT.DTPL d ON d.PLNSCDGO = p.PLNSCDGO
 WHERE p.PLNSCDAL = 21 AND p.PJRQCDGO = 1236 AND d.DTPLAXL1 = 61;


-- BLOQUE 1 — TABLA
CREATE TABLE CRD.DSSB (
    DSSBCDGO NUMBER            NOT NULL,
    CRARCDGO NUMBER            NOT NULL,
    ENTDCDGO NUMBER            NOT NULL,
    DSSBTPDS NUMBER            NOT NULL,
    PRSTCDGO NUMBER,
    TPAPCDGO NUMBER,
    DSSBVLAH NUMBER(18,2),
    DSSBVLPR NUMBER(18,2),
    DSSBPGTR NUMBER,
    DSSBASNT NUMBER,
    DSSBESTD NUMBER  DEFAULT 1 NOT NULL,
    DSSBOBSR VARCHAR2(1000),
    DSSBUSRG VARCHAR2(50)      NOT NULL,
    DSSBFCRG TIMESTAMP         NOT NULL,
    DSSBUSMD VARCHAR2(50),
    DSSBFCMD TIMESTAMP
);

ALTER TABLE CRD.DSSB ADD CONSTRAINT PK_DSSB PRIMARY KEY (DSSBCDGO);
CREATE SEQUENCE CRD.SQ_DSSBCDGO START WITH 1 INCREMENT BY 1 NOCACHE;

ALTER TABLE CRD.DSSB ADD CONSTRAINT FK_DSSB_CRAR FOREIGN KEY (CRARCDGO) REFERENCES CRD.CRAR (CRARCDGO);
ALTER TABLE CRD.DSSB ADD CONSTRAINT FK_DSSB_ENTD FOREIGN KEY (ENTDCDGO) REFERENCES CRD.ENTD (ENTDCDGO);
ALTER TABLE CRD.DSSB ADD CONSTRAINT FK_DSSB_PRST FOREIGN KEY (PRSTCDGO) REFERENCES CRD.PRST (PRSTCDGO);
ALTER TABLE CRD.DSSB ADD CONSTRAINT FK_DSSB_TPAP FOREIGN KEY (TPAPCDGO) REFERENCES CRD.TPAP (TPAPCDGO);

-- 1 = siguiente cuota (préstamo opcional), 2 = aporte (tipo obligatorio), 3 = devolución (ni préstamo ni tipo)
ALTER TABLE CRD.DSSB ADD CONSTRAINT CK_DSSB_DESTINO CHECK (
       (DSSBTPDS = 1 AND TPAPCDGO IS NULL)
    OR (DSSBTPDS = 2 AND TPAPCDGO IS NOT NULL AND PRSTCDGO IS NULL)
    OR (DSSBTPDS = 3 AND TPAPCDGO IS NULL AND PRSTCDGO IS NULL));
ALTER TABLE CRD.DSSB ADD CONSTRAINT CK_DSSB_ESTADO CHECK (DSSBESTD IN (0, 1));
ALTER TABLE CRD.DSSB ADD CONSTRAINT CK_DSSB_VALOR  CHECK ((DSSBVLAH IS NULL OR DSSBVLAH >= 0) AND (DSSBVLPR IS NULL OR DSSBVLPR >= 0));

-- Un solo destino ACTIVO por (carga, partícipe); los anulados (0) no cuentan.
CREATE UNIQUE INDEX CRD.UX_DSSB_CARGA_PARTICIPE
    ON CRD.DSSB (CASE WHEN DSSBESTD = 1 THEN CRARCDGO END, CASE WHEN DSSBESTD = 1 THEN ENTDCDGO END);
CREATE INDEX CRD.IDX_DSSB_CARGA ON CRD.DSSB (CRARCDGO);

COMMENT ON TABLE  CRD.DSSB IS 'Destino del sobrante de una carga Petro/ARCH por participe: 1 siguiente cuota, 2 aporte, 3 devolucion (B8, sql/357)';
COMMENT ON COLUMN CRD.DSSB.DSSBTPDS IS '1 SIGUIENTE_CUOTA, 2 APORTE, 3 DEVOLUCION (com.saa.rubros.DestinoSobrante)';
COMMENT ON COLUMN CRD.DSSB.DSSBVLAH IS 'Valor aplicado o devuelto cuyo dinero entro por una fila de APORTES (puente aux1 3); lo escribe el proceso';
COMMENT ON COLUMN CRD.DSSB.DSSBVLPR IS 'Valor aplicado o devuelto cuyo dinero entro por una fila de PRESTAMOS (puente aux1 4); lo escribe el proceso';
COMMENT ON COLUMN CRD.DSSB.DSSBPGTR IS 'Pago programado de Tesoreria (PGS.PGTR.PGTRCDGO), sin FK; solo destino 3';
COMMENT ON COLUMN CRD.DSSB.DSSBASNT IS 'Asiento que llevo el valor a socios por pagar (CNT.ASNT.ASNTCDGO), sin FK; solo destino 3';


-- BLOQUE 2 — SEMILLA: línea 61 de la plantilla 21 (CrdLineaAsiento.DEVOLUCION_DESCUENTO_PARTICIPE),
--   HABER (2), cuenta de hoy 2.3.90.90.10 SOCIOS POR PAGAR (decisión del usuario U3, 2026-11-01).
--   Antes, la secuencia de DTPL tiene que ir por delante del MAX (ver 356 bloque 0.4).
INSERT INTO CNT.DTPL (DTPLCDGO, PLNSCDGO, PLNNCDGO, DTPLAXL1, DTPLAXL2, DTPLMVMN, DTPLDSCR, DTPLESTD)
SELECT CNT.SQ_DTPLCDGO.NEXTVAL, p.PLNSCDGO, n.PLNNCDGO, 61, 0, 2,
       'Devolucion al participe de un descuento Petro/ARCH (socios por pagar)', 1
  FROM CNT.PLNS p
  JOIN CNT.PLNN n ON n.PJRQCDGO = p.PJRQCDGO AND n.PLNNCNTA = '2.3.90.90.10'
 WHERE p.PLNSCDAL = 21 AND p.PJRQCDGO = 1236
   AND NOT EXISTS (SELECT 1 FROM CNT.DTPL d WHERE d.PLNSCDGO = p.PLNSCDGO AND d.DTPLAXL1 = 61);
-- (!) "1 fila insertada".
COMMIT;


-- BLOQUE 3 — CONTROL DESPUÉS
-- 3.1 Tabla, PK, 4 FK, 3 CHECK habilitados.
SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CRD' AND TABLE_NAME = 'DSSB' AND CONSTRAINT_NAME NOT LIKE 'SYS_%' ORDER BY 1;
-- 3.2 Índices (2) y secuencia (1).
SELECT INDEX_NAME, UNIQUENESS FROM ALL_INDEXES WHERE OWNER = 'CRD' AND TABLE_NAME = 'DSSB' ORDER BY 1;
SELECT SEQUENCE_NAME, LAST_NUMBER FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'CRD' AND SEQUENCE_NAME = 'SQ_DSSBCDGO';
-- 3.3 La línea 61: 1 fila, cuenta 2.3.90.90.10, MOV 2.
SELECT d.DTPLAXL1, d.DTPLAXL2, d.DTPLMVMN, n.PLNNCNTA, d.DTPLDSCR, d.DTPLESTD
  FROM CNT.PLNS p JOIN CNT.DTPL d ON d.PLNSCDGO = p.PLNSCDGO JOIN CNT.PLNN n ON n.PLNNCDGO = d.PLNNCDGO
 WHERE p.PLNSCDAL = 21 AND p.PJRQCDGO = 1236 AND d.DTPLAXL1 = 61;


