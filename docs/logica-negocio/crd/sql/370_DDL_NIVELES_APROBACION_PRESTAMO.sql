-- 370 — DDL. omen-saa-1, 2026-11-07. Niveles de aprobación configurables del préstamo.
-- Pedido del usuario (2026-11-07): «Hagamos niveles de aprobación configurables. Que puedan ser por tipo de
-- préstamo, monto, plazo. Y con eso determinar el número de niveles de aprobación y qué usuario aprueba en cada
-- nivel». Diseño: docs/logica-negocio/crd/DISENO-SOLICITUD-V1-AUTORIZACION-Y-REGLAS-OTORGAMIENTO.md §B4.
-- Nombres RGAP, NVAP, UNAP, APPR reservados en REGISTRO-RESERVAS-EQUIPOS.md §5 (2026-11-07).
--
--   CRD.RGAP  regla: tipo de préstamo + rango de monto + rango de plazo → una lista de niveles
--   CRD.NVAP  nivel de una regla (orden 1..n). El NÚMERO de niveles es cuántos NVAP activos tiene la regla
--   CRD.UNAP  usuario que puede aprobar un nivel (uno o varios por nivel; basta uno)
--   CRD.APPR  bitácora de aprobaciones de cada préstamo, nivel por nivel
--
-- Usuarios = SCP.PJRQ (PJRQCDGO). UNAPPJRQ y APPRPJRQ van SIN FK a propósito: es otro esquema y una FK entre
-- esquemas exige GRANT REFERENCES (mismo patrón que PRSTIDPG y DSSBPGTR).
--
-- ⛔ Va ANTES del EAR que mapee estas tablas. Es aditivo: sin reglas activas el préstamo se aprueba como hoy (§B4).
-- Correr bloque por bloque, en orden.
-- =====================================================================================

-- BLOQUE 0 — CONTROL ANTES. ESPERADO: 0 filas.
SELECT OWNER, TABLE_NAME FROM ALL_TABLES WHERE OWNER = 'CRD' AND TABLE_NAME IN ('RGAP', 'NVAP', 'UNAP', 'APPR');


-- BLOQUE 1 — REGLA
CREATE TABLE CRD.RGAP (
    RGAPCDGO NUMBER            NOT NULL,
    RGAPNMBR VARCHAR2(200)     NOT NULL,
    TPPRCDGO NUMBER,
    RGAPMNMN NUMBER(18,2),
    RGAPMNMX NUMBER(18,2),
    RGAPPLMN NUMBER,
    RGAPPLMX NUMBER,
    RGAPPRRD NUMBER  DEFAULT 100 NOT NULL,
    RGAPESTD NUMBER  DEFAULT 1   NOT NULL,
    RGAPUSRG VARCHAR2(50)      NOT NULL,
    RGAPFCRG TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RGAPUSMD VARCHAR2(50),
    RGAPFCMD TIMESTAMP
);
ALTER TABLE CRD.RGAP ADD CONSTRAINT PK_RGAP PRIMARY KEY (RGAPCDGO);
CREATE SEQUENCE CRD.SQ_RGAPCDGO START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE CRD.RGAP ADD CONSTRAINT FK_RGAP_TPPR FOREIGN KEY (TPPRCDGO) REFERENCES CRD.TPPR (TPPRCDGO);
ALTER TABLE CRD.RGAP ADD CONSTRAINT CK_RGAP_ESTADO CHECK (RGAPESTD IN (0, 1));
ALTER TABLE CRD.RGAP ADD CONSTRAINT CK_RGAP_MONTO  CHECK (RGAPMNMN IS NULL OR RGAPMNMX IS NULL OR RGAPMNMN <= RGAPMNMX);
ALTER TABLE CRD.RGAP ADD CONSTRAINT CK_RGAP_PLAZO  CHECK (RGAPPLMN IS NULL OR RGAPPLMX IS NULL OR RGAPPLMN <= RGAPPLMX);

COMMENT ON TABLE  CRD.RGAP IS 'Regla de aprobacion de prestamos: tipo + rango de monto + rango de plazo -> niveles (NVAP) (sql/370)';
COMMENT ON COLUMN CRD.RGAP.TPPRCDGO IS 'Tipo de prestamo (CRD.TPPR); nulo = cualquier tipo';
COMMENT ON COLUMN CRD.RGAP.RGAPMNMN IS 'Monto desde (inclusive); nulo = sin minimo';
COMMENT ON COLUMN CRD.RGAP.RGAPMNMX IS 'Monto hasta (inclusive); nulo = sin maximo';
COMMENT ON COLUMN CRD.RGAP.RGAPPLMN IS 'Plazo en cuotas desde (inclusive); nulo = sin minimo';
COMMENT ON COLUMN CRD.RGAP.RGAPPLMX IS 'Plazo en cuotas hasta (inclusive); nulo = sin maximo';
COMMENT ON COLUMN CRD.RGAP.RGAPPRRD IS 'Prioridad: si varias reglas aplican gana la de numero menor; empate = error de configuracion';
COMMENT ON COLUMN CRD.RGAP.RGAPESTD IS '1 activa, 0 inactiva';


-- BLOQUE 2 — NIVEL
CREATE TABLE CRD.NVAP (
    NVAPCDGO NUMBER            NOT NULL,
    RGAPCDGO NUMBER            NOT NULL,
    NVAPORDN NUMBER            NOT NULL,
    NVAPNMBR VARCHAR2(200)     NOT NULL,
    NVAPESTD NUMBER  DEFAULT 1 NOT NULL,
    NVAPUSRG VARCHAR2(50)      NOT NULL,
    NVAPFCRG TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    NVAPUSMD VARCHAR2(50),
    NVAPFCMD TIMESTAMP
);
ALTER TABLE CRD.NVAP ADD CONSTRAINT PK_NVAP PRIMARY KEY (NVAPCDGO);
CREATE SEQUENCE CRD.SQ_NVAPCDGO START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE CRD.NVAP ADD CONSTRAINT FK_NVAP_RGAP FOREIGN KEY (RGAPCDGO) REFERENCES CRD.RGAP (RGAPCDGO);
ALTER TABLE CRD.NVAP ADD CONSTRAINT CK_NVAP_ESTADO CHECK (NVAPESTD IN (0, 1));
ALTER TABLE CRD.NVAP ADD CONSTRAINT CK_NVAP_ORDEN  CHECK (NVAPORDN >= 1);
-- Un solo nivel ACTIVO por (regla, orden).
CREATE UNIQUE INDEX CRD.UX_NVAP_REGLA_ORDEN
    ON CRD.NVAP (CASE WHEN NVAPESTD = 1 THEN RGAPCDGO END, CASE WHEN NVAPESTD = 1 THEN NVAPORDN END);
CREATE INDEX CRD.IDX_NVAP_RGAP ON CRD.NVAP (RGAPCDGO);

COMMENT ON TABLE  CRD.NVAP IS 'Nivel de aprobacion de una regla (RGAP); se aprueban en orden 1..n (sql/370)';
COMMENT ON COLUMN CRD.NVAP.NVAPORDN IS 'Orden del nivel dentro de la regla, desde 1';
COMMENT ON COLUMN CRD.NVAP.NVAPNMBR IS 'Nombre del nivel (p. ej. Jefe de Credito, Gerencia General, CAD)';


-- BLOQUE 3 — USUARIO POR NIVEL
CREATE TABLE CRD.UNAP (
    UNAPCDGO NUMBER            NOT NULL,
    NVAPCDGO NUMBER            NOT NULL,
    UNAPPJRQ NUMBER            NOT NULL,
    UNAPESTD NUMBER  DEFAULT 1 NOT NULL,
    UNAPUSRG VARCHAR2(50)      NOT NULL,
    UNAPFCRG TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNAPUSMD VARCHAR2(50),
    UNAPFCMD TIMESTAMP
);
ALTER TABLE CRD.UNAP ADD CONSTRAINT PK_UNAP PRIMARY KEY (UNAPCDGO);
CREATE SEQUENCE CRD.SQ_UNAPCDGO START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE CRD.UNAP ADD CONSTRAINT FK_UNAP_NVAP FOREIGN KEY (NVAPCDGO) REFERENCES CRD.NVAP (NVAPCDGO);
ALTER TABLE CRD.UNAP ADD CONSTRAINT CK_UNAP_ESTADO CHECK (UNAPESTD IN (0, 1));
CREATE UNIQUE INDEX CRD.UX_UNAP_NIVEL_USUARIO
    ON CRD.UNAP (CASE WHEN UNAPESTD = 1 THEN NVAPCDGO END, CASE WHEN UNAPESTD = 1 THEN UNAPPJRQ END);
CREATE INDEX CRD.IDX_UNAP_NVAP ON CRD.UNAP (NVAPCDGO);

COMMENT ON TABLE  CRD.UNAP IS 'Usuario habilitado para aprobar un nivel (NVAP); basta uno de los del nivel (sql/370)';
COMMENT ON COLUMN CRD.UNAP.UNAPPJRQ IS 'Usuario (SCP.PJRQ.PJRQCDGO), sin FK por ser otro esquema';


-- BLOQUE 4 — BITÁCORA DE APROBACIONES DEL PRÉSTAMO
CREATE TABLE CRD.APPR (
    APPRCDGO NUMBER            NOT NULL,
    PRSTCDGO NUMBER            NOT NULL,
    RGAPCDGO NUMBER            NOT NULL,
    NVAPCDGO NUMBER            NOT NULL,
    APPRORDN NUMBER            NOT NULL,
    APPRNMNV VARCHAR2(200)     NOT NULL,
    APPRPJRQ NUMBER            NOT NULL,
    APPRUSRO VARCHAR2(50)      NOT NULL,
    APPRDCSN NUMBER            NOT NULL,
    APPRFCHA TIMESTAMP         DEFAULT CURRENT_TIMESTAMP NOT NULL,
    APPROBSR VARCHAR2(1000),
    APPRESTD NUMBER  DEFAULT 1 NOT NULL,
    APPRUSMD VARCHAR2(50),
    APPRFCMD TIMESTAMP
);
ALTER TABLE CRD.APPR ADD CONSTRAINT PK_APPR PRIMARY KEY (APPRCDGO);
CREATE SEQUENCE CRD.SQ_APPRCDGO START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE CRD.APPR ADD CONSTRAINT FK_APPR_PRST FOREIGN KEY (PRSTCDGO) REFERENCES CRD.PRST (PRSTCDGO);
ALTER TABLE CRD.APPR ADD CONSTRAINT FK_APPR_RGAP FOREIGN KEY (RGAPCDGO) REFERENCES CRD.RGAP (RGAPCDGO);
ALTER TABLE CRD.APPR ADD CONSTRAINT FK_APPR_NVAP FOREIGN KEY (NVAPCDGO) REFERENCES CRD.NVAP (NVAPCDGO);
ALTER TABLE CRD.APPR ADD CONSTRAINT CK_APPR_DECISION CHECK (APPRDCSN IN (1, 2));
ALTER TABLE CRD.APPR ADD CONSTRAINT CK_APPR_ESTADO   CHECK (APPRESTD IN (0, 1));
-- Un nivel se aprueba UNA vez por préstamo mientras la aprobación esté vigente.
CREATE UNIQUE INDEX CRD.UX_APPR_PRESTAMO_ORDEN
    ON CRD.APPR (CASE WHEN APPRESTD = 1 THEN PRSTCDGO END, CASE WHEN APPRESTD = 1 THEN APPRORDN END);
CREATE INDEX CRD.IDX_APPR_PRST ON CRD.APPR (PRSTCDGO);

COMMENT ON TABLE  CRD.APPR IS 'Aprobaciones de un prestamo nivel por nivel (sql/370)';
COMMENT ON COLUMN CRD.APPR.APPRORDN IS 'Orden del nivel aprobado (copia de NVAPORDN al aprobar)';
COMMENT ON COLUMN CRD.APPR.APPRNMNV IS 'Nombre del nivel al aprobar (copia de NVAPNMBR; la configuracion puede cambiar despues)';
COMMENT ON COLUMN CRD.APPR.APPRPJRQ IS 'Usuario que decidio (SCP.PJRQ.PJRQCDGO), sin FK por ser otro esquema';
COMMENT ON COLUMN CRD.APPR.APPRUSRO IS 'Nombre del usuario que decidio (SCP.PJRQ.PJRQNMBR)';
COMMENT ON COLUMN CRD.APPR.APPRDCSN IS '1 aprobado, 2 negado';
COMMENT ON COLUMN CRD.APPR.APPRESTD IS '1 vigente, 0 invalidada (el prestamo cambio despues de aprobar este nivel)';


-- BLOQUE 5 — CONTROL DESPUÉS
-- 5.1 Constraints por tabla (sin SYS_): RGAP 5, NVAP 4, UNAP 3, APPR 6.
SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CRD' AND TABLE_NAME IN ('RGAP', 'NVAP', 'UNAP', 'APPR') AND CONSTRAINT_NAME NOT LIKE 'SYS_%'
 ORDER BY TABLE_NAME, CONSTRAINT_NAME;
-- 5.2 Secuencias: 4.
SELECT SEQUENCE_NAME, LAST_NUMBER FROM ALL_SEQUENCES
 WHERE SEQUENCE_OWNER = 'CRD' AND SEQUENCE_NAME IN ('SQ_RGAPCDGO', 'SQ_NVAPCDGO', 'SQ_UNAPCDGO', 'SQ_APPRCDGO');
-- 5.3 Sin ninguna regla activa: ESPERADO 0 (así el préstamo se sigue aprobando como hoy hasta configurar).
SELECT COUNT(*) AS REGLAS_ACTIVAS FROM CRD.RGAP WHERE RGAPESTD = 1;


