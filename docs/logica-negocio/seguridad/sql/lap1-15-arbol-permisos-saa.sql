-- CONTROL D — Cuantos nodos tiene ahora la jerarquia 11, y como se reparten.
-- Esperado: SAA 305, SEGURIDAD 75, RAIZ 1, TOTAL 381 (eran 742, se borraron 666,
-- se insertaron 305).
SELECT 'SAA'                  AS SUBARBOL,
       COUNT(*)               AS NODOS
  FROM SCP.PJRQ
 WHERE PGSPCDGO = 11
 START WITH PJRQCDGO = 1253
CONNECT BY PRIOR PJRQCDGO = PJRQCDPD AND PGSPCDGO = 11
UNION ALL
SELECT 'SEGURIDAD Y AUDITORIA', COUNT(*)
  FROM SCP.PJRQ
 WHERE PGSPCDGO = 11
 START WITH PJRQCDGO = 42
CONNECT BY PRIOR PJRQCDGO = PJRQCDPD AND PGSPCDGO = 11
UNION ALL
SELECT 'TOTAL JERARQUIA 11', COUNT(*) FROM SCP.PJRQ WHERE PGSPCDGO = 11
UNION ALL
SELECT 'OTRAS JERARQUIAS (empresas, usuarios)', COUNT(*)
  FROM SCP.PJRQ WHERE PGSPCDGO <> 11;

-- CONTROL E — Ningun nodo puede quedar apuntando a un padre que ya no existe.
-- Es el control que atrapa un DELETE que se llevo de mas.
-- Esperado: NINGUNA FILA.
SELECT h.PJRQCDGO, h.PJRQNMBR, h.PJRQCDPD AS PADRE_INEXISTENTE
  FROM SCP.PJRQ h
 WHERE h.PGSPCDGO = 11
   AND h.PJRQCDPD <> 0
   AND NOT EXISTS (SELECT 1 FROM SCP.PJRQ p
