--------------------------------------------------------------------------------
-- LO UNICO QUE NO SE PUEDE OLVIDAR AL LEER ESTE ARCHIVO
--
-- SCP.PJRQ NO es solo el arbol de permisos: es TAMBIEN la tabla de EMPRESAS y de
-- USUARIOS del sistema. Empresa.java y Usuario.java mapean esta misma tabla,
-- discriminadas por PGSPCDGO (5 y 12 empresa, 9 usuario, 11 permisos).
--
-- Por eso TODOS los DELETE de este archivo llevan "PGSPCDGO = 11" Y ADEMAS un
-- CONNECT BY acotado a los tres subarboles. Un DELETE mas ancho borraria empresas
-- y usuarios, y se llevaria media base por integridad referencial.
--
-- Si alguna vez hay que modificar este script: ese filtro no es decorativo.
--------------------------------------------------------------------------------
-- QUE SE CONSERVA Y QUE NO
--
--   93   RAIZ SISTEMAS           -> SE CONSERVA. Sin la raiz el arbol no dibuja.
--   42   SEGURIDAD Y AUDITORIA   -> SE CONSERVA (75 nodos). Es el arbol del propio
--                                   modulo con el que se administran los permisos.
--   482  PCC                     -> SE BORRA (325 nodos)
--   315  CID                     -> SE BORRA (150 nodos)
--   979  ACT                     -> SE BORRA (191 nodos)
--                                   666 nodos en total
--
--   1253 SAA                     -> SE INSERTA, 305 nodos (ids 1253 a 1557)
--------------------------------------------------------------------------------
-- COMO SE CORRE: de arriba a abajo. Los CONTROL A/B/C son de solo lectura y hay
-- que MIRAR su resultado antes de seguir. El PASO 1 hace un respaldo completo del
-- arbol 11 en una tabla propia; el bloque de reverso del final, comentado,
-- restaura desde ese respaldo.
--------------------------------------------------------------------------------


--------------------------------------------------------------------------------
-- CONTROL A — Los permisos ya asignados (SCP.PENP) contra lo que se va a borrar.
--
-- El usuario reporto 2 filas en PENP. Este control dice si alguna apunta a un
-- nodo que vamos a borrar. Muestra las filas completas y ademas resuelve a que
-- nodo apunta cada una, que es la unica forma de decidir sin adivinar.
--
-- Esperado: DESTINO distinto de "SE BORRA" en las dos filas.
-- Si alguna dice "SE BORRA", el PASO 2 la elimina.
--------------------------------------------------------------------------------
SELECT p.*,
       (SELECT j.PJRQNMBR FROM SCP.PJRQ j
         WHERE j.PJRQCDGO = p.PJRQCDGO)                        AS NODO_APUNTADO,
       (SELECT j.PGSPCDGO FROM SCP.PJRQ j
         WHERE j.PJRQCDGO = p.PJRQCDGO)                        AS JERARQUIA_DEL_NODO,
       CASE WHEN p.PJRQCDGO IN (
                 SELECT PJRQCDGO FROM SCP.PJRQ
                  WHERE PGSPCDGO = 11
                  START WITH PJRQCDGO IN (482, 315, 979)
                CONNECT BY PRIOR PJRQCDGO = PJRQCDPD AND PGSPCDGO = 11)
            THEN 'SE BORRA'
            ELSE 'sobrevive'
       END                                                     AS DESTINO
  FROM SCP.PENP p;


--------------------------------------------------------------------------------
-- CONTROL B — Recuento de lo que se va a borrar, con el MISMO CONNECT BY que usa
-- el DELETE del PASO 3. Esperado: 666.
--------------------------------------------------------------------------------
SELECT COUNT(*) AS NODOS_A_BORRAR
  FROM SCP.PJRQ
 WHERE PGSPCDGO = 11
 START WITH PJRQCDGO IN (482, 315, 979)
CONNECT BY PRIOR PJRQCDGO = PJRQCDPD
       AND PGSPCDGO = 11;


--------------------------------------------------------------------------------
-- CONTROL C — El rango 1253..1557 tiene que estar libre en TODA la tabla, no solo
-- en la jerarquia 11: los ids son unicos globalmente porque la PK es PJRQCDGO
-- solo. Esperado: 0.
--------------------------------------------------------------------------------
SELECT COUNT(*) AS FILAS_QUE_ESTORBAN_EN_EL_RANGO
  FROM SCP.PJRQ
 WHERE PJRQCDGO BETWEEN 1253 AND 1557;


--------------------------------------------------------------------------------
-- PASO 1 — RESPALDO. Es lo que hace reversible todo lo que viene despues.
-- Copia las 742 filas de la jerarquia 11: lo que se borra Y lo que se conserva.
--------------------------------------------------------------------------------
CREATE TABLE SCP.PJRQ_BKP_LAP1 AS
SELECT * FROM SCP.PJRQ WHERE PGSPCDGO = 11;

-- Y el respaldo de los permisos asignados. Son 2 filas, y valen igual.
CREATE TABLE SCP.PENP_BKP_LAP1 AS
SELECT * FROM SCP.PENP;

-- Control del respaldo. Esperado: 742 y 2. Si no cuadra, PARAR: sin respaldo
-- valido no se sigue.
SELECT (SELECT COUNT(*) FROM SCP.PJRQ_BKP_LAP1) AS ARBOL_RESPALDADO,
       (SELECT COUNT(*) FROM SCP.PENP_BKP_LAP1) AS PERMISOS_RESPALDADOS
  FROM DUAL;


--------------------------------------------------------------------------------
-- PASO 2 — Borrar los permisos asignados que apuntan a nodos que van a
-- desaparecer. Decision del usuario: "se borran los permisos ya asignados".
--
-- Va ANTES del PASO 3 porque SCP.PENP tiene FK_PENP_PJRQ contra SCP.PJRQ: si
-- quedara una fila apuntando a un nodo borrado, el PASO 3 fallaria con ORA-02292
-- y no borraria nada.
--
-- Segun el CONTROL A esto deberia borrar 0 filas. Se deja igual: el script tiene
-- que ser correcto por si mismo, no por lo que hoy haya en la tabla.
--------------------------------------------------------------------------------
DELETE FROM SCP.PENP
 WHERE PJRQCDGO IN (
       SELECT PJRQCDGO FROM SCP.PJRQ
        WHERE PGSPCDGO = 11
        START WITH PJRQCDGO IN (482, 315, 979)
      CONNECT BY PRIOR PJRQCDGO = PJRQCDPD AND PGSPCDGO = 11);


--------------------------------------------------------------------------------
-- PASO 3 — Borrar los tres sistemas ajenos.
--
-- No hace falta borrar hijos antes que padres: PJRQ no tiene clave foranea sobre
-- si misma. PJRQCDPD no es FK — verificado en el CONTROL 3 del lap1-13, donde las
-- unicas constraints son PK_PJRQ, FK_PJRQ_PGSP y UN_PJRQ_01. Un solo DELETE.
--
-- Esperado: 666 filas.
--------------------------------------------------------------------------------
DELETE FROM SCP.PJRQ
 WHERE PGSPCDGO = 11
   AND PJRQCDGO IN (
       SELECT PJRQCDGO FROM SCP.PJRQ
        WHERE PGSPCDGO = 11
