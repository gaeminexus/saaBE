-- 337_D038_REGISTRO_G41.sql — D-038 (29-oct-2026): historia del estado de los partícipes reportado en la G41.
--
-- Por qué: la G41 es mensual y solo trae a los partícipes "que ingresen, actualicen o eliminen información" (Manual de
-- Estructuras de Catastros FCPC v1.2, 17-02-2023, §2.2). I = nuevo; A = cambió el estado civil, el estado del partícipe
-- o la relación laboral. Para saber qué cambió hay que conocer lo último reportado: RPR.SG41 guarda, por sujeto y período,
-- el estado del partícipe (A activo / P pasivo, tabla 195). GeneracionG41ServiceImpl lo lee (estado anterior = fila con
-- el mayor período < mes) y lo alimenta (origen EJECUCION). Sustituye la marca ENTDIDST = 9, que no tenía fecha.
--
-- Se aplica UNA vez, ANTES de desplegar el WAR que trae D-038. SQL puro (cliente JDBC). Orden: 1 DDL, 2 semilla de
-- mayo 2025 (G42 presentada), 3 G41 presentada en mayo 2025, 4 controles. Los pasos 2 y 3 se pueden re-ejecutar.
--
-- SEMILLA: el estado de mayo 2025 sale de lo que la Superintendencia ya recibió. Estado A = aportó en el mes = aporte
-- personal del mes > 0 en la G42 presentada (HM42APPR); P si no. La G41 de mayo (HM41) manda donde existe. Así el primer
-- mes que genera el SAA (junio 2025) solo reporta lo que cambió después de lo presentado. El período 202505 queda como
-- "mes presentado": si se regenera mayo, la G41 reproduce las 66 filas de la HM41 y no toca el registro.

-- 1. DDL
CREATE TABLE RPR.SG41 (
    SG41CDGO NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SG41TIDP VARCHAR2(1)   NOT NULL,
    SG41IDPR VARCHAR2(13)  NOT NULL,
    SG41ESPR VARCHAR2(1)   NOT NULL,
    SG41ESRG VARCHAR2(1),
    SG41PRDO NUMBER(6,0)   NOT NULL,
    SG41ORGN VARCHAR2(10)  NOT NULL,
    SG41EJRD NUMBER(19,0),
    SG41FCRG DATE          NOT NULL,
    CONSTRAINT PK_SG41 PRIMARY KEY (SG41CDGO),
    CONSTRAINT UK_SG41_IDPR_PRDO UNIQUE (SG41IDPR, SG41PRDO),
    CONSTRAINT CK_SG41_ESPR CHECK (SG41ESPR IN ('A','P')),
    CONSTRAINT CK_SG41_ESRG CHECK (SG41ESRG IS NULL OR SG41ESRG IN ('I','A','E')),
    CONSTRAINT CK_SG41_ORGN CHECK (SG41ORGN IN ('SEMILLA','HM41','EJECUCION'))
);

CREATE INDEX IX_SG41_PRDO ON RPR.SG41 (SG41PRDO);

COMMENT ON TABLE  RPR.SG41          IS 'D-038: historia del estado del partícipe reportado en la G41 (una fila por sujeto y período)';
COMMENT ON COLUMN RPR.SG41.SG41CDGO IS 'Código único';
COMMENT ON COLUMN RPR.SG41.SG41TIDP IS 'Tipo de identificación del partícipe (C/E)';
COMMENT ON COLUMN RPR.SG41.SG41IDPR IS 'Identificación del partícipe';
COMMENT ON COLUMN RPR.SG41.SG41ESPR IS 'Estado del partícipe desde ese período (tabla 195: A activo, P pasivo)';
COMMENT ON COLUMN RPR.SG41.SG41ESRG IS 'Estado del registro enviado en la G41 (tabla 11: I, A, E); nulo = semilla, no se envió';
COMMENT ON COLUMN RPR.SG41.SG41PRDO IS 'Período AAAAMM';
COMMENT ON COLUMN RPR.SG41.SG41ORGN IS 'SEMILLA (G42 presentada mayo 2025) | HM41 (G41 presentada mayo 2025) | EJECUCION (G41 del SAA)';
COMMENT ON COLUMN RPR.SG41.SG41EJRD IS 'EJRD de la G41 que lo reportó (solo EJECUCION)';
COMMENT ON COLUMN RPR.SG41.SG41FCRG IS 'Fecha de registro';

-- 2. Semilla: estado de mayo 2025 de cada sujeto de la G42 presentada que no está en la G41 presentada
INSERT INTO RPR.SG41 (SG41TIDP, SG41IDPR, SG41ESPR, SG41PRDO, SG41ORGN, SG41FCRG)
SELECT NVL(TRIM(h.HM42TIDP),'C'), TRIM(h.HM42IDPR), CASE WHEN h.HM42APPR > 0 THEN 'A' ELSE 'P' END, 202505, 'SEMILLA', SYSDATE
FROM RPR.HM42 h
WHERE TRIM(h.HM42IDPR) IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM RPR.HM41 g WHERE TRIM(g.HM41IDPR) = TRIM(h.HM42IDPR))
  AND NOT EXISTS (SELECT 1 FROM RPR.SG41 s WHERE s.SG41IDPR = TRIM(h.HM42IDPR) AND s.SG41PRDO = 202505);

-- 3. G41 presentada y aceptada en mayo 2025 (66 filas: 1 I + 65 A)
INSERT INTO RPR.SG41 (SG41TIDP, SG41IDPR, SG41ESPR, SG41ESRG, SG41PRDO, SG41ORGN, SG41FCRG)
SELECT NVL(TRIM(g.HM41TIDP),'C'), TRIM(g.HM41IDPR), TRIM(g.HM41ESPR), TRIM(g.HM41ESRG), 202505, 'HM41', SYSDATE
FROM RPR.HM41 g
WHERE TRIM(g.HM41IDPR) IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM RPR.SG41 s WHERE s.SG41IDPR = TRIM(g.HM41IDPR) AND s.SG41PRDO = 202505);

COMMIT;

-- 4. Controles (esperado con la base del 29-oct-2026): SEMILLA 4.519 (A = aportó en mayo según la G42 presentada);
--    HM41 66 (29 A, incluido el I, y 37 P); total 202505 = 4.585 = filas de la HM42.
SELECT SG41ORGN, SG41ESPR, SG41ESRG, COUNT(*) sujetos FROM RPR.SG41 GROUP BY SG41ORGN, SG41ESPR, SG41ESRG ORDER BY 1, 2, 3;
SELECT (SELECT COUNT(*) FROM RPR.SG41 WHERE SG41PRDO = 202505) registro_202505,
       (SELECT COUNT(*) FROM RPR.HM42) hm42 FROM dual;

-- 4.b Reproducción de mayo con la regla (estado de abril por aportes 9/11 > 0 del período efectivo abril; estado de mayo
--     el reportado en la G42 presentada): esperado 66 emitidos, 64 coinciden con la HM41 (las 4 diferencias vienen de que
--     abril sale de APRT y no de la G42 de abril, que no tenemos).
WITH abr AS (
  SELECT DISTINCT a.ENTDCDGO FROM CRD.APRT a
  WHERE a.TPAPCDGO IN (9, 11) AND a.APRTVLRR > 0
    AND (NVL(a.APRTIDST, 4) <> 0 AND NOT (NVL(a.APRTTPMV, 0) = 5 AND NVL(a.APRTGLSA, ' ') LIKE '%reverso APRT %'))
    AND (CASE WHEN a.APRTPRDV IS NOT NULL THEN a.APRTPRDV WHEN a.APRTVLRR > 0 THEN TRUNC(a.APRTFCTR,'MM') END) = DATE '2025-04-01'),
u AS (
  SELECT TRIM(h.HM42IDPR) idpr,
         CASE WHEN EXISTS (SELECT 1 FROM RPR.HM41 z WHERE TRIM(z.HM41IDPR) = TRIM(h.HM42IDPR) AND z.HM41ESRG = 'I') THEN NULL
              WHEN e.ENTDCDGO IN (SELECT ENTDCDGO FROM abr) THEN 'A' ELSE 'P' END ant,
         CASE WHEN h.HM42APPR > 0 THEN 'A' ELSE 'P' END act
  FROM RPR.HM42 h LEFT JOIN CRD.ENTD e ON TRIM(e.ENTDNMID) = TRIM(h.HM42IDPR))
SELECT SUM(CASE WHEN ant IS NULL OR ant <> act THEN 1 ELSE 0 END) emitidos_regla,
       SUM(CASE WHEN (ant IS NULL OR ant <> act) AND g.HM41IDPR IS NOT NULL AND g.HM41ESPR = act THEN 1 ELSE 0 END) coinciden_hm41
FROM u LEFT JOIN RPR.HM41 g ON TRIM(g.HM41IDPR) = u.idpr;

