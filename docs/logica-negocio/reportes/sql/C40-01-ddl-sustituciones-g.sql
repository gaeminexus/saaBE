-- C40-01-ddl-sustituciones-g.sql — C40 (23-nov-2026): sustituciones que se aplican al generar las G de un período.
--
-- Por qué: una estructura que ya se presentó a la Superintendencia no siempre se puede volver a cargar. Cuando la Super
-- obliga a presentar una operación distinta de lo que dice el SAA (D-154: la G45 de junio 2025 se cargó sin el sujeto
-- de la operación 71174 y no se puede recargar), el SAA tiene que poder regenerar ese mes tal como se presentó. La
-- contabilidad y la cartera del SAA no cambian: la sustitución vive solo en las estructuras G
-- (SustitucionReporteGServiceImpl la aplica dentro de la generación de cada estructura, antes de la validación previa).
--
-- Acciones:
--   REEMPLAZAR  (G46, G48)  en la fila de la operación SSTGNMOP: número reportado SSTGOPRP y, si SSTGOPSJ tiene valor,
--                           el sujeto del préstamo SSTGOPSJ; SSTGFCHA, si tiene valor, cambia la fecha de concesión (G46).
--   AGREGAR     (G46)       alta del préstamo SSTGNMOP con número SSTGOPRP, sujeto propio (o el de SSTGOPSJ) y fecha
--                           de concesión SSTGFCHA. La G51 (garantía) y la G45 (sujeto) salen de la G46 de la misma
--                           ejecución, así que no necesitan sustitución propia.
--               (G49)       cancelación de la operación SSTGOPRP a nombre del sujeto del préstamo SSTGOPSJ, con fecha
--                           SSTGFCHA y forma SSTGFRMA.
-- Una sustitución activa que no encuentra su fila hace fallar la estructura: es la señal de que algo cambió.
--
-- Se aplica UNA vez, ANTES de desplegar el WAR que trae C40. SQL puro (cliente JDBC). Sin datos personales: los sujetos
-- se toman por número de operación. Idempotente (el paso 2 no repite filas). Termina SIN COMMIT.

-- 1. DDL
CREATE TABLE RPR.SSTG (
    SSTGCDGO NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SSTGPRDO NUMBER(6,0)   NOT NULL,
    SSTGESTR VARCHAR2(3)   NOT NULL,
    SSTGACCN VARCHAR2(10)  NOT NULL,
    SSTGNMOP VARCHAR2(32)  NOT NULL,
    SSTGOPRP VARCHAR2(32)  NOT NULL,
    SSTGOPSJ VARCHAR2(32),
    SSTGFCHA DATE,
    SSTGFRMA VARCHAR2(2),
    SSTGDCSN VARCHAR2(20)  NOT NULL,
    SSTGOBSR VARCHAR2(500),
    SSTGESTD NUMBER(1,0)   DEFAULT 1 NOT NULL,
    SSTGFCRG DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_SSTG PRIMARY KEY (SSTGCDGO),
    CONSTRAINT UK_SSTG UNIQUE (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP),
    CONSTRAINT CK_SSTG_ESTR CHECK (SSTGESTR IN ('G46','G48','G49')),
    CONSTRAINT CK_SSTG_ACCN CHECK (SSTGACCN IN ('REEMPLAZAR','AGREGAR')),
    CONSTRAINT CK_SSTG_ESTD CHECK (SSTGESTD IN (0,1))
);

COMMENT ON TABLE  RPR.SSTG          IS 'C40: sustituciones que se aplican al generar las G de un período (lo presentado a la Super que difiere del SAA)';
COMMENT ON COLUMN RPR.SSTG.SSTGCDGO IS 'Código único';
COMMENT ON COLUMN RPR.SSTG.SSTGPRDO IS 'Período AAAAMM de la ejecución donde se aplica';
COMMENT ON COLUMN RPR.SSTG.SSTGESTR IS 'Estructura: G46, G48, G49';
COMMENT ON COLUMN RPR.SSTG.SSTGACCN IS 'REEMPLAZAR (fila existente) | AGREGAR (fila nueva)';
COMMENT ON COLUMN RPR.SSTG.SSTGNMOP IS 'Número de operación (idAsoprep) del préstamo en el SAA';
COMMENT ON COLUMN RPR.SSTG.SSTGOPRP IS 'Número de operación que se reporta';
COMMENT ON COLUMN RPR.SSTG.SSTGOPSJ IS 'Operación (idAsoprep) cuyo sujeto se reporta; vacío = el sujeto del préstamo SSTGNMOP';
COMMENT ON COLUMN RPR.SSTG.SSTGFCHA IS 'Fecha de concesión (G46) o de cancelación (G49) que se reporta; vacío = la del SAA';
COMMENT ON COLUMN RPR.SSTG.SSTGFRMA IS 'Forma de cancelación (G49, tabla 39)';
COMMENT ON COLUMN RPR.SSTG.SSTGDCSN IS 'Decisión que la sustenta (DECISIONES-Y-PARTIDAS.md)';
COMMENT ON COLUMN RPR.SSTG.SSTGOBSR IS 'Observación';
COMMENT ON COLUMN RPR.SSTG.SSTGESTD IS '1 activa, 0 inactiva';
COMMENT ON COLUMN RPR.SSTG.SSTGFCRG IS 'Fecha de registro';

-- 2. Sustituciones de D-154 (operación 71174). Junio y julio 2025: la operación se presentó como 71148 a nombre del
--    sujeto de la 70595 (las G45, G46 y G49 de julio se cargaron sin el cambio y no se pueden recargar, 24-nov-2026).
--    Agosto 2025: se cancela la 71148 y se da de alta la 71174 a nombre de su titular, con concesión 01/08/2025.
INSERT INTO RPR.SSTG (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, SSTGFCHA, SSTGFRMA, SSTGDCSN, SSTGOBSR)
SELECT 202506, 'G46', 'REEMPLAZAR', '71174', '71148', '70595', NULL, NULL, 'D-154', 'G45 de junio cargada sin el sujeto de la 71174'
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM RPR.SSTG WHERE SSTGPRDO = 202506 AND SSTGESTR = 'G46' AND SSTGACCN = 'REEMPLAZAR' AND SSTGNMOP = '71174');
INSERT INTO RPR.SSTG (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, SSTGFCHA, SSTGFRMA, SSTGDCSN, SSTGOBSR)
SELECT 202506, 'G48', 'REEMPLAZAR', '71174', '71148', '70595', NULL, NULL, 'D-154', 'G45 de junio cargada sin el sujeto de la 71174'
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM RPR.SSTG WHERE SSTGPRDO = 202506 AND SSTGESTR = 'G48' AND SSTGACCN = 'REEMPLAZAR' AND SSTGNMOP = '71174');
INSERT INTO RPR.SSTG (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, SSTGFCHA, SSTGFRMA, SSTGDCSN, SSTGOBSR)
SELECT 202507, 'G48', 'REEMPLAZAR', '71174', '71148', '70595', NULL, NULL, 'D-154', 'G45, G46 y G49 de julio cargadas sin el cambio: la 71148 sigue activa'
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM RPR.SSTG WHERE SSTGPRDO = 202507 AND SSTGESTR = 'G48' AND SSTGACCN = 'REEMPLAZAR' AND SSTGNMOP = '71174');
INSERT INTO RPR.SSTG (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, SSTGFCHA, SSTGFRMA, SSTGDCSN, SSTGOBSR)
SELECT 202508, 'G46', 'AGREGAR', '71174', '71174', NULL, DATE '2025-08-01', NULL, 'D-154', 'Alta de la 71174 a nombre de su titular (en junio y julio se presentó como 71148)'
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM RPR.SSTG WHERE SSTGPRDO = 202508 AND SSTGESTR = 'G46' AND SSTGACCN = 'AGREGAR' AND SSTGNMOP = '71174');
INSERT INTO RPR.SSTG (SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, SSTGFCHA, SSTGFRMA, SSTGDCSN, SSTGOBSR)
SELECT 202508, 'G49', 'AGREGAR', '71174', '71148', '70595', DATE '2025-08-01', 'O', 'D-154', 'Cancelación de la 71148 presentada en junio y julio'
  FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM RPR.SSTG WHERE SSTGPRDO = 202508 AND SSTGESTR = 'G49' AND SSTGACCN = 'AGREGAR' AND SSTGNMOP = '71174');

-- 3. Control. ESPERADO: 5 filas activas de D-154 (202506 G46 y G48, 202507 G48, 202508 G46 y G49).
SELECT SSTGPRDO, SSTGESTR, SSTGACCN, SSTGNMOP, SSTGOPRP, SSTGOPSJ, TO_CHAR(SSTGFCHA, 'DD/MM/YYYY') FECHA, SSTGFRMA, SSTGDCSN, SSTGESTD
  FROM RPR.SSTG ORDER BY SSTGPRDO, SSTGESTR, SSTGACCN;

