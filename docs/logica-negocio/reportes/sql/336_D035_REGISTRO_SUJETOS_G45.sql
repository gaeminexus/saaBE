-- 336_D035_REGISTRO_SUJETOS_G45.sql — D-035 (29-oct-2026): registro de sujetos ya reportados a la Superintendencia en la G45.
--
-- Por qué: el control de la G46 exige que el sujeto "conste en la base de datos de la estructura G45" (Manual de
-- Estructuras de Operaciones de Crédito FCPC v2.4, 18-08-2023, §5.2). La Superintendencia mantiene una base acumulada:
-- la G45 del mes solo trae los sujetos de las operaciones del mes que todavía no están en ella. RPR.SG45 es la copia
-- local de esa base (GeneracionG45ServiceImpl la lee y la alimenta).
--
-- Se aplica UNA vez, ANTES de desplegar el WAR que trae D-035. SQL puro (cliente JDBC). Orden: 1 DDL, 2 semilla,
-- 3 HM45, 4 controles. Los pasos 2 y 3 se pueden re-ejecutar: no insertan sujetos que ya estén.
--
-- SEMILLA — supuesto a confirmar con ASOPREP: no se encontró en el expediente ni en la base la fecha en que ASOPREP
-- empezó a reportar la G45 (RPR.EJRC empieza en 2025-06; RPR.HM45 solo trae mayo 2025). Se toma como "ya reportado"
-- a todo sujeto con un préstamo concedido antes de mayo 2025 cuya vida (hasta el vencimiento de su última cuota)
-- llega al período 2021-07 o después. Cualquier fecha en (2019-08-31, 2021-07-31] reproduce exactamente la G45 de
-- mayo 2025 (10 sujetos de 73); se elige la MÁS TARDÍA (semilla más chica: ante la duda el SAA vuelve a reportar a un
-- sujeto, lo que la G45 admite, en lugar de omitir uno nuevo, que haría rechazar la G46). Evidencia sin cédulas:
-- cuadreSuper/03-trabajo/meses/2025-06/resultados/33-g45-*.

-- 1. DDL
CREATE TABLE RPR.SG45 (
    SG45CDGO NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    SG45TIDS VARCHAR2(1)   NOT NULL,
    SG45IDSJ VARCHAR2(13)  NOT NULL,
    SG45PRDO NUMBER(6,0)   NOT NULL,
    SG45ORGN VARCHAR2(10)  NOT NULL,
    SG45EJRD NUMBER(19,0),
    SG45FCRG DATE          NOT NULL,
    CONSTRAINT PK_SG45 PRIMARY KEY (SG45CDGO),
    CONSTRAINT UK_SG45_IDSJ UNIQUE (SG45IDSJ),
    CONSTRAINT CK_SG45_ORGN CHECK (SG45ORGN IN ('SEMILLA','HM45','EJECUCION'))
);

COMMENT ON TABLE  RPR.SG45          IS 'D-035: sujetos de riesgo ya reportados a la Superintendencia en la G45 (base acumulada)';
COMMENT ON COLUMN RPR.SG45.SG45CDGO IS 'Código único';
COMMENT ON COLUMN RPR.SG45.SG45TIDS IS 'Tipo de identificación del sujeto (C/E)';
COMMENT ON COLUMN RPR.SG45.SG45IDSJ IS 'Identificación del sujeto';
COMMENT ON COLUMN RPR.SG45.SG45PRDO IS 'Primer período reportado AAAAMM (SEMILLA = 202504: antes de mayo 2025)';
COMMENT ON COLUMN RPR.SG45.SG45ORGN IS 'SEMILLA | HM45 (G45 presentada mayo 2025) | EJECUCION (G45 generada por el SAA)';
COMMENT ON COLUMN RPR.SG45.SG45EJRD IS 'EJRD de la G45 que lo reportó (solo EJECUCION)';
COMMENT ON COLUMN RPR.SG45.SG45FCRG IS 'Fecha de registro';

-- 2. Semilla: reportados antes de mayo 2025 (sin los 10 de la HM45, que se reportaron en mayo)
INSERT INTO RPR.SG45 (SG45TIDS, SG45IDSJ, SG45PRDO, SG45ORGN, SG45FCRG)
SELECT 'C', x.idsj, 202504, 'SEMILLA', SYSDATE
FROM (SELECT DISTINCT TRIM(e.ENTDNMID) idsj
      FROM CRD.PRST p JOIN CRD.ENTD e ON e.ENTDCDGO = p.ENTDCDGO
      WHERE p.PRSTFCHA < DATE '2025-05-01'
        AND NVL(p.PRSTIDST,0) NOT IN (0,1,6,7,12)
        AND TRIM(e.ENTDNMID) IS NOT NULL
        AND (SELECT MAX(d.DTPRFCVN) FROM CRD.DTPR d WHERE d.PRSTCDGO = p.PRSTCDGO) >= DATE '2021-07-01') x
WHERE NOT EXISTS (SELECT 1 FROM RPR.HM45 h WHERE TRIM(h.HM45IDSJ) = x.idsj)
  AND NOT EXISTS (SELECT 1 FROM RPR.SG45 s WHERE s.SG45IDSJ = x.idsj);

-- 3. G45 presentada y aceptada en mayo 2025
INSERT INTO RPR.SG45 (SG45TIDS, SG45IDSJ, SG45PRDO, SG45ORGN, SG45FCRG)
SELECT NVL(TRIM(h.HM45TIDS),'C'), TRIM(h.HM45IDSJ), 202505, 'HM45', SYSDATE
FROM RPR.HM45 h
WHERE TRIM(h.HM45IDSJ) IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM RPR.SG45 s WHERE s.SG45IDSJ = TRIM(h.HM45IDSJ));

COMMIT;

-- 4. Controles (esperado con la base del 29-oct-2026: SEMILLA 1.726, HM45 10; los 73 sujetos de la HM46 en el registro;
--    de ellos, los 10 de la HM45 con período 202505 y los 63 restantes con 202504)
SELECT SG45ORGN, SG45PRDO, COUNT(*) sujetos FROM RPR.SG45 GROUP BY SG45ORGN, SG45PRDO ORDER BY 1, 2;

SELECT s.SG45PRDO, COUNT(DISTINCT TRIM(h.HM46IDSJ)) sujetos_hm46
FROM RPR.HM46 h LEFT JOIN RPR.SG45 s ON s.SG45IDSJ = TRIM(h.HM46IDSJ)
GROUP BY s.SG45PRDO ORDER BY 1;
