-- B.3 CONTROL 3 — esquema viejo: 1.313 anulados con la etiqueta, 0 vigentes
SELECT NVL(PGPRANUL, 0) AS ANULADO, COUNT(*) AS N, SUM(PGPRVLRR) AS TOTAL,
       MIN(PGPRMTAN) AS MOTIVO_MIN, MAX(PGPRMTAN) AS MOTIVO_MAX
