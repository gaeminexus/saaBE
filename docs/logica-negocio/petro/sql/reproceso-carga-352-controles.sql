-- B.2 CONTROL 2 — todos los pagos vigentes de la 352 fechados 30-jun-2025, con CRARCDGO y PRSTCDGO (esperado: una sola fila, OK)
SELECT TRUNC(PGPRFCHA) AS FECHA, COUNT(*) AS N, SUM(PGPRVLRR) AS TOTAL,
