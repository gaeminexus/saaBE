-- =============================================================================
-- BLOQUE 1 - Columnas de reembolso en PGS.FCTC (script 07)
-- =============================================================================

DECLARE
    PROCEDURE agrega(p_col VARCHAR2, p_tipo VARCHAR2) IS
        c NUMBER;
    BEGIN
        SELECT COUNT(*) INTO c FROM all_tab_columns
         WHERE owner = 'PGS' AND table_name = 'FCTC' AND column_name = p_col;
        IF c = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PGS.FCTC ADD (' || p_col || ' ' || p_tipo || ')';
            DBMS_OUTPUT.PUT_LINE('  + FCTC.' || p_col || ' agregada');
        ELSE
            DBMS_OUTPUT.PUT_LINE('  = FCTC.' || p_col || ' ya existia, se omite');
        END IF;
    END;
BEGIN
    agrega('FCTCESRM', 'NUMBER(1) DEFAULT 0');
    agrega('FCTCCDRM', 'VARCHAR2(2)');
    agrega('FCTCTCRM', 'NUMBER(14,2)');
    agrega('FCTCTBRM', 'NUMBER(14,2)');
    agrega('FCTCTIRM', 'NUMBER(14,2)');
END;
/


-- =============================================================================
-- BLOQUE 2 - Columnas en PGS.DCXP (scripts 07 y 08)
-- =============================================================================

DECLARE
    PROCEDURE agrega(p_col VARCHAR2, p_tipo VARCHAR2) IS
        c NUMBER;
    BEGIN
        SELECT COUNT(*) INTO c FROM all_tab_columns
         WHERE owner = 'PGS' AND table_name = 'DCXP' AND column_name = p_col;
        IF c = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PGS.DCXP ADD (' || p_col || ' ' || p_tipo || ')';
            DBMS_OUTPUT.PUT_LINE('  + DCXP.' || p_col || ' agregada');
        ELSE
            DBMS_OUTPUT.PUT_LINE('  = DCXP.' || p_col || ' ya existia, se omite');
        END IF;
    END;
BEGIN
    -- del script 07
    agrega('DCXPESRM', 'NUMBER(1) DEFAULT 0');
    -- del script 08. Nullables a proposito: los documentos historicos se
    -- cargaron a mano y no tienen resultado del SRI. Un DCXPORXM nulo se lee
    -- como "manual, anterior a este cambio".
    agrega('DCXPORXM', 'NUMBER(1)');
    agrega('DCXPRSRI', 'VARCHAR2(30)');
    agrega('DCXPMSRI', 'VARCHAR2(500)');
    agrega('DCXPFDSC', 'TIMESTAMP');
END;
/


-- =============================================================================
-- BLOQUE 3 - Tabla PGS.RMBF con su PK y FK (script 07)
-- =============================================================================

DECLARE
    c NUMBER;
BEGIN
    SELECT COUNT(*) INTO c FROM all_tables
     WHERE owner = 'PGS' AND table_name = 'RMBF';

    IF c > 0 THEN
        DBMS_OUTPUT.PUT_LINE('  = PGS.RMBF ya existia, se omite la creacion');
    ELSE
        EXECUTE IMMEDIATE '
        CREATE TABLE PGS.RMBF (
            RMBFCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
            RMBFFCTC NUMBER          NOT NULL,
            RMBFTIPR VARCHAR2(2),
            RMBFIDPR VARCHAR2(20)    NOT NULL,
            RMBFCDPS VARCHAR2(3)     DEFAULT ''593'',
            RMBFTPPR VARCHAR2(2),
            RMBFCDDC VARCHAR2(2),
            RMBFESTB VARCHAR2(3),
            RMBFPTEM VARCHAR2(3),
            RMBFSCNL VARCHAR2(9),
            RMBFFEMS DATE,
            RMBFNAUT VARCHAR2(49),
            RMBFBSCR NUMBER(14,2)    DEFAULT 0,
            RMBFBSGR NUMBER(14,2)    DEFAULT 0,
            RMBFTRIV NUMBER(5,2),
            RMBFVLIV NUMBER(14,2)    DEFAULT 0,
            RMBFVLIC NUMBER(14,2)    DEFAULT 0,
            RMBFTTAL NUMBER(14,2)    DEFAULT 0,
            RMBFPRDC NUMBER(11),
            RMBFORGN NUMBER(1)       DEFAULT 1,
            RMBFESTD NUMBER(1)       DEFAULT 1,
            RMBFOBSR VARCHAR2(500),
            CONSTRAINT PK_RMBF PRIMARY KEY (RMBFCDGO),
            CONSTRAINT FK_RMBF_FACTURA FOREIGN KEY (RMBFFCTC) REFERENCES PGS.FCTC(ID)
        )';
        DBMS_OUTPUT.PUT_LINE('  + PGS.RMBF creada con PK_RMBF y FK_RMBF_FACTURA');
    END IF;
END;
/


-- =============================================================================
-- BLOQUE 4 - Indices de PGS.RMBF (script 07)
-- =============================================================================

DECLARE
    PROCEDURE crea_indice(p_nombre VARCHAR2, p_columna VARCHAR2) IS
        c NUMBER;
    BEGIN
        SELECT COUNT(*) INTO c FROM all_indexes
         WHERE owner = 'PGS' AND index_name = p_nombre;
        IF c = 0 THEN
            EXECUTE IMMEDIATE 'CREATE INDEX PGS.' || p_nombre
                           || ' ON PGS.RMBF (' || p_columna || ')';
            DBMS_OUTPUT.PUT_LINE('  + indice ' || p_nombre || ' creado');
        ELSE
            DBMS_OUTPUT.PUT_LINE('  = indice ' || p_nombre || ' ya existia, se omite');
        END IF;
    END;
BEGIN
    crea_indice('IDX_RMBF_FACTURA',  'RMBFFCTC');
    crea_indice('IDX_RMBF_PRODUCTO', 'RMBFPRDC');
END;
/


