COMMENT ON COLUMN PGS.FCTC.FCTCESRM IS 'Es factura de reembolso de gastos: 0=No 1=Si';

COMMENT ON COLUMN PGS.FCTC.FCTCCDRM IS 'codDocReembolso del XML (tabla 3 SRI, normalmente 41)';

COMMENT ON COLUMN PGS.FCTC.FCTCTCRM IS 'totalComprobantesReembolso (del XML o recalculado desde PGS.RMBF)';

COMMENT ON COLUMN PGS.FCTC.FCTCTBRM IS 'totalBaseImponibleReembolso';

COMMENT ON COLUMN PGS.FCTC.FCTCTIRM IS 'totalImpuestoReembolso';

COMMENT ON COLUMN PGS.DCXP.DCXPESRM IS 'Marcado como factura de reembolso de gastos: 0=No 1=Si';

COMMENT ON COLUMN PGS.DCXP.DCXPORXM IS 'Origen del XML: 1=Manual (subido por el usuario) 2=SRI (descargado por servicio web). NULL=historico anterior al cambio';

COMMENT ON COLUMN PGS.DCXP.DCXPRSRI IS 'Resultado del ultimo intento de descarga: DESCARGADO, FUERA_VENTANA, NO_ENCONTRADO, NO_AUTORIZADO, ERROR_CONEXION';

COMMENT ON COLUMN PGS.DCXP.DCXPMSRI IS 'Mensaje devuelto por el SRI, o el motivo calculado localmente cuando no se llego a llamar';

COMMENT ON COLUMN PGS.DCXP.DCXPFDSC IS 'Fecha y hora del ultimo intento de descarga del XML desde el SRI';

COMMENT ON TABLE PGS.RMBF IS 'Detalle de reembolsos de gastos de una factura de compra (un registro por documento sustento / reembolsoDetalle del XML SRI, ANEXO 5 Ficha Tecnica)';

COMMIT;


