-- =====================================================
-- TABLA: RPR.CCPB (CreditoCuotasPrestamosBanda)
-- DESCRIPCIÓN: Detalle del CCPM por operación, rubro y banda: capital por vencer y vencido
--              bandeado POR CUOTA con la cuenta contable de la configuración de bandas del
--              producto, y los rubros interés vencido, mora, desgravamen, seguro de incendio y
--              provisión por operación. Lo usa el Resumen Financiero para comparar cada línea
--              con el saldo contable de su cuenta.
-- FECHA: 2026-11-11
-- =====================================================
CREATE TABLE RPR.CCPB (
    CCPBCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    CCPBEJCC NUMBER NOT NULL,                 -- ejecución (RPR.EJCC)
    CCPBNMOP VARCHAR2(50),                    -- número de operación (= CCPM.CCPMNMOP)
    CCPBPRST NUMBER,                          -- préstamo (CRD.PRST)
    CCPBPRDC NUMBER,                          -- producto (CRD.PRDC)
    CCPBTPPR NUMBER,                          -- tipo de préstamo (CRD.TPPR)
    CCPBRBRO VARCHAR2(30) NOT NULL,           -- rubro
    CCPBNMBN NUMBER,                          -- número de banda (rubros de capital)
    CCPBETQT VARCHAR2(100),                   -- etiqueta de la banda
    CCPBCNTA VARCHAR2(50),                    -- cuenta contable de la banda
    CCPBVLOR NUMBER(18,2),                    -- valor
    CONSTRAINT PK_CCPB PRIMARY KEY (CCPBCDGO),
    CONSTRAINT FK_CCPB_EJCC FOREIGN KEY (CCPBEJCC) REFERENCES RPR.EJCC(EJCCCDGO),
    CONSTRAINT CK_CCPB_RBRO CHECK (CCPBRBRO IN ('CAPITAL_POR_VENCER', 'CAPITAL_VENCIDO', 'INTERES_VENCIDO',
                                                'MORA', 'DESGRAVAMEN', 'SEGURO_INCENDIO', 'PROVISION'))
);

CREATE INDEX IX_CCPB_EJCC ON RPR.CCPB (CCPBEJCC, CCPBRBRO);

COMMENT ON TABLE RPR.CCPB IS 'Detalle del CCPM por operacion, rubro y banda (C27)';
COMMENT ON COLUMN RPR.CCPB.CCPBCDGO IS 'Codigo (PK)';
COMMENT ON COLUMN RPR.CCPB.CCPBEJCC IS 'Ejecucion de reportes de cartera (RPR.EJCC)';
COMMENT ON COLUMN RPR.CCPB.CCPBNMOP IS 'Numero de operacion (PRST.PRSTIDAS)';
COMMENT ON COLUMN RPR.CCPB.CCPBPRST IS 'Prestamo (CRD.PRST)';
COMMENT ON COLUMN RPR.CCPB.CCPBPRDC IS 'Producto (CRD.PRDC)';
COMMENT ON COLUMN RPR.CCPB.CCPBTPPR IS 'Tipo de prestamo (CRD.TPPR)';
COMMENT ON COLUMN RPR.CCPB.CCPBRBRO IS 'CAPITAL_POR_VENCER, CAPITAL_VENCIDO, INTERES_VENCIDO, MORA, DESGRAVAMEN, SEGURO_INCENDIO, PROVISION';
COMMENT ON COLUMN RPR.CCPB.CCPBNMBN IS 'Numero de banda de la configuracion del producto (rubros de capital)';
COMMENT ON COLUMN RPR.CCPB.CCPBETQT IS 'Etiqueta de la banda';
COMMENT ON COLUMN RPR.CCPB.CCPBCNTA IS 'Cuenta contable de la banda (con puntos)';
COMMENT ON COLUMN RPR.CCPB.CCPBVLOR IS 'Valor del rubro, redondeado a 2 decimales';

