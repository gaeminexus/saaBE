-- BLOQUE 2 — TITULOS OFICIALES (Res. SBS-2013-0507: "estado de situacion financiera"; el resto, su nombre)
UPDATE CNT.RPRT SET RPRTTTLO = 'ESTADO DE SITUACIÓN FINANCIERA' WHERE PJRQCDGO = 1236 AND RPRTALTR IN (1, 2);
UPDATE CNT.RPRT SET RPRTTTLO = 'ESTADO DE RESULTADOS' WHERE PJRQCDGO = 1236 AND RPRTALTR = 3;
UPDATE CNT.RPRT SET RPRTTTLO = 'BALANCE DE PRUEBA' WHERE PJRQCDGO = 1236 AND RPRTALTR = 4;
UPDATE CNT.RPRT SET RPRTTTLO = 'BALANCE DE COMPROBACIÓN' WHERE PJRQCDGO = 1236 AND RPRTALTR = 5;

