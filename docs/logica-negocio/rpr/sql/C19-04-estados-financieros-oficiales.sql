-- BLOQUE 1 — CONTROL ANTES
-- 1.1 Tipos de reporte de la 1236 (ESPERADO: 84 BALANCE GENERAL/1, 85 BALANCE GENERAL 1/2, 87 ESTADO DE RESULTADOS/3,
--     88 BALANCE DE PRUEBA/4, 89 BALANCE DE COMPROBACION/5; mas B17/6 y FLUJO/7 si ya corrieron C19-02/03).
SELECT RPRTCDGO, RPRTNMBR, RPRTALTR, RPRTTTLO FROM CNT.RPRT WHERE PJRQCDGO = 1236 ORDER BY RPRTALTR;
-- 1.2 El rubro 250 no debe existir. ESPERADO: 0 filas.
