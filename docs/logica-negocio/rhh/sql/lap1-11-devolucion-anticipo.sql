-- ---------------------------------------------------------------------
-- CONTROL 5 — despues: la tabla y el producto.
-- ---------------------------------------------------------------------
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER = 'RHH' AND TABLE_NAME = 'DVAN';

SELECT CONSTRAINT_NAME, CONSTRAINT_TYPE, SEARCH_CONDITION
  FROM ALL_CONSTRAINTS WHERE OWNER = 'RHH' AND TABLE_NAME = 'DVAN';

SELECT p.CODIGO, p.NOMBRE, c.PLNNCNTA AS CUENTA
  FROM PGS.PRDP p
  JOIN PGS.GRPP g ON g.GRPPCDGO = p.GRUPOPRODUCTO
  JOIN CNT.PLNN c ON c.PLNNCDGO = g.PLNNCDGO
 WHERE p.CODIGO = 'RHH-DVAN';


-- ---------------------------------------------------------------------
-- CONTROL 6 — el que importa: la cuenta del producto tiene que ser la
--             MISMA de la linea 14. Debe decir COINCIDE.
-- ---------------------------------------------------------------------
SELECT g.PLNNCDGO AS CUENTA_DEL_PRODUCTO,
       d.PLNNCDGO AS CUENTA_DE_LA_PLANTILLA,
       CASE WHEN g.PLNNCDGO = d.PLNNCDGO THEN 'COINCIDE' ELSE 'NO COINCIDE' END AS DIAGNOSTICO
  FROM PGS.PRDP p
  JOIN PGS.GRPP g ON g.GRPPCDGO = p.GRUPOPRODUCTO
  CROSS JOIN (SELECT PLNNCDGO FROM CNT.DTPL WHERE DTPLLNEA = 14 AND ROWNUM = 1) d
 WHERE p.CODIGO = 'RHH-DVAN';


