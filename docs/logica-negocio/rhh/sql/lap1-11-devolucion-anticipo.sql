-- =====================================================================
-- BLOQUE 2: producto de cobro para la devolucion
-- =====================================================================
-- procesarIngreso arma el HABER con la cuenta del GRUPO del producto. La
-- devolucion tiene que acreditar la MISMA cuenta que la entrega del
-- anticipo debito: RhhLineaAsiento.CUENTAS_POR_COBRAR_EMPLEADOS (14).
--
-- ⛔ Si acreditara otra, el saldo del empleado no se cerraria nunca y no se
--    veria hasta un cierre.

-- ---------------------------------------------------------------------
-- CONTROL 3 — que cuenta usa hoy la linea 14. Es el insumo del INSERT.
-- ---------------------------------------------------------------------
SELECT d.DTPLLNEA AS LINEA,
       p.PLNNCDGO AS ID_CUENTA,
       p.PLNNCNTA AS CUENTA,
       p.PLNNNMBR AS NOMBRE_CUENTA
  FROM CNT.DTPL d
  JOIN CNT.PLNN p ON p.PLNNCDGO = d.PLNNCDGO
 WHERE d.DTPLLNEA = 14;

-- ⚠️ Nombres de CNT.DTPL sin verificar contra el DDL real. Si falla:
--      SELECT COLUMN_NAME FROM ALL_TAB_COLUMNS
--       WHERE OWNER='CNT' AND TABLE_NAME='DTPL' ORDER BY COLUMN_ID;


-- ---------------------------------------------------------------------
-- CONTROL 4 — quiza el producto ya existe y no hace falta crear nada.
-- ---------------------------------------------------------------------
SELECT p.ID, p.CODIGO, p.NOMBRE, g.GRPPNMBR, c.PLNNCNTA
  FROM PGS.PRDP p
  LEFT JOIN PGS.GRPP g ON g.GRPPCDGO = p.GRUPOPRODUCTO
  LEFT JOIN CNT.PLNN c ON c.PLNNCDGO = g.PLNNCDGO
 WHERE UPPER(p.NOMBRE) LIKE '%EMPLEADO%'
    OR UPPER(p.NOMBRE) LIKE '%ANTICIPO%'
    OR UPPER(g.GRPPNMBR) LIKE '%COBRAR%EMPLEADO%';


