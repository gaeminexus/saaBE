-- QUE RESUELVE
-- Hoy un anticipo solo se recupera descontandolo del rol. Si el empleado
-- deposita la plata en la cuenta de la empresa no hay donde registrarlo,
-- no se contabiliza, y el descuento del mes se le aplica igual: se le cobra
-- dos veces.
--
-- Cada devolucion genera un ingreso de tesoreria (TSR.INGR), que ya
-- contabiliza DEBE banco / HABER la cuenta del producto y emite el
-- movimiento bancario para la conciliacion.
--
-- VA ANTES DEL WAR. La entidad mapea estas columnas.
-- Diseno: docs/logica-negocio/rhh/API-DEVOLUCION-ANTICIPO.md
-- =====================================================================


-- ---------------------------------------------------------------------
-- CONTROL 1 — la tabla no debe existir todavia (0 filas esperadas).
-- ---------------------------------------------------------------------
SELECT OWNER, TABLE_NAME FROM ALL_TABLES WHERE TABLE_NAME = 'DVAN';


-- ---------------------------------------------------------------------
-- CONTROL 2 — foto de los anticipos vivos, para tener el antes.
--             ANTEESTD: 1 solicitado, 2 aprobado, 3 pagado,
--                       4 en descuento, 5 cancelado, 6 anulado.
-- ---------------------------------------------------------------------
SELECT a.ANTEESTD AS ESTADO,
       COUNT(*)   AS ANTICIPOS,
       SUM(NVL(a.ANTESLDD, 0)) AS SALDO_PENDIENTE
  FROM RHH.ANTE a
 GROUP BY a.ANTEESTD
 ORDER BY a.ANTEESTD;


-- =====================================================================
-- BLOQUE 1: RHH.DVAN
-- =====================================================================
CREATE TABLE RHH.DVAN (
    DVANCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    ANTECDGO NUMBER NOT NULL,
    DVANFCHA DATE NOT NULL,
    DVANVLOR NUMBER(18,2) NOT NULL,
    CNBCCDGO NUMBER NOT NULL,
    DVANRFRN VARCHAR2(200),
    DVANOBSR VARCHAR2(2000),
    INGRCDGO NUMBER,
    DVANASNT NUMBER,
    DVANESTD NUMBER DEFAULT 1 NOT NULL,
    DVANMTAN VARCHAR2(500),
    DVANFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DVANUSAR NUMBER,
    CONSTRAINT PK_DVAN PRIMARY KEY (DVANCDGO),
    CONSTRAINT FK_DVAN_ANTE FOREIGN KEY (ANTECDGO) REFERENCES RHH.ANTE(ANTECDGO),
    CONSTRAINT CK_DVAN_ESTD CHECK (DVANESTD IN (1,2)),
    CONSTRAINT CK_DVAN_VLOR CHECK (DVANVLOR > 0)
);

CREATE INDEX RHH.IDX_DVAN_ANTE ON RHH.DVAN(ANTECDGO);
CREATE INDEX RHH.IDX_DVAN_CNBC ON RHH.DVAN(CNBCCDGO);

COMMENT ON TABLE RHH.DVAN IS 'Devolucion de un anticipo: el empleado deposita en la cuenta de la empresa en vez de que se le descuente del rol';
COMMENT ON COLUMN RHH.DVAN.DVANCDGO IS 'PK';
COMMENT ON COLUMN RHH.DVAN.ANTECDGO IS 'Anticipo devuelto (RHH.ANTE)';
COMMENT ON COLUMN RHH.DVAN.DVANFCHA IS 'Fecha real del deposito, no la de captura';
COMMENT ON COLUMN RHH.DVAN.DVANVLOR IS 'Valor devuelto; puede ser parcial y puede haber varias por anticipo';
COMMENT ON COLUMN RHH.DVAN.CNBCCDGO IS 'Cuenta bancaria de la empresa donde deposito (TSR.CNBC)';
COMMENT ON COLUMN RHH.DVAN.DVANRFRN IS 'Numero de papeleta o de transferencia';
COMMENT ON COLUMN RHH.DVAN.INGRCDGO IS 'Ingreso de tesoreria generado (TSR.INGR). Id crudo a proposito: Ingreso tiene varios ManyToOne EAGER';
COMMENT ON COLUMN RHH.DVAN.DVANASNT IS 'Asiento del ingreso (CNT.ASNT)';
COMMENT ON COLUMN RHH.DVAN.DVANESTD IS '1 Vigente, 2 Anulada';

