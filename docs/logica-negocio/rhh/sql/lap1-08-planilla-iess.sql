SELECT (SELECT MAX(PRBRCDGO) FROM SCP.PRBR) AS MAX_PRBR,
       (SELECT MAX(PDTRCDGO) FROM SCP.PDTR) AS MAX_PDTR
  FROM DUAL;


-- =====================================================================
-- BLOQUE 1: RHH.PLIS — cabecera de la planilla emitida por el IESS
-- =====================================================================
CREATE TABLE RHH.PLIS (
    PLISCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    PJRQCDGO NUMBER NOT NULL,
    PRDNCDGO NUMBER NOT NULL,
    PLISTIPO NUMBER NOT NULL,
    PLISNMCM VARCHAR2(50) NOT NULL,
    PLISFCEM DATE,
    PLISFCMX DATE,
    PLISVLIS NUMBER(18,2) NOT NULL,
    PLISVLCT NUMBER(18,2),
    PLISDIFR NUMBER(18,2),
    PLISESTD NUMBER DEFAULT 1 NOT NULL,
    PLISFCPG DATE,
    PLISASNT NUMBER,
    PLISOBSR VARCHAR2(1000),
    PLISMTAN VARCHAR2(500),
    PLISFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PLISUSAR NUMBER,
    CONSTRAINT PK_PLIS PRIMARY KEY (PLISCDGO),
    CONSTRAINT FK_PLIS_PJRQ FOREIGN KEY (PJRQCDGO) REFERENCES SCP.PJRQ(PJRQCDGO),
    CONSTRAINT FK_PLIS_PRDN FOREIGN KEY (PRDNCDGO) REFERENCES RHH.PRDN(PRDNCDGO),
    CONSTRAINT CK_PLIS_TIPO CHECK (PLISTIPO IN (1,2,3,4)),
    CONSTRAINT CK_PLIS_ESTD CHECK (PLISESTD IN (1,2,3,4))
);

CREATE INDEX RHH.IDX_PLIS_PRDN ON RHH.PLIS(PRDNCDGO);
CREATE INDEX RHH.IDX_PLIS_PJRQ ON RHH.PLIS(PJRQCDGO);

-- El comprobante del portal no se repite dentro de una empresa y un tipo.
-- Se deja fuera el estado a proposito: una planilla anulada y una nueva con
-- el MISMO comprobante seria volver a registrar lo ya rechazado.
CREATE UNIQUE INDEX RHH.UX_PLIS_COMPROBANTE ON RHH.PLIS(PJRQCDGO, PLISTIPO, PLISNMCM);

COMMENT ON TABLE RHH.PLIS IS 'Planilla emitida por el portal del IESS: se captura para conciliar contra la planilla de control antes de pagar';
COMMENT ON COLUMN RHH.PLIS.PLISCDGO IS 'PK';
COMMENT ON COLUMN RHH.PLIS.PJRQCDGO IS 'Empresa (SCP.PJRQ)';
COMMENT ON COLUMN RHH.PLIS.PRDNCDGO IS 'Periodo de nomina (RHH.PRDN)';
COMMENT ON COLUMN RHH.PLIS.PLISTIPO IS 'Tipo de planilla (rubro 330): 1 rol normal, 2 quirografarios, 3 hipotecarios, 4 fondos de reserva';
COMMENT ON COLUMN RHH.PLIS.PLISNMCM IS 'Numero de comprobante que emitio el portal';
COMMENT ON COLUMN RHH.PLIS.PLISFCEM IS 'Fecha de emision del comprobante';
COMMENT ON COLUMN RHH.PLIS.PLISFCMX IS 'Fecha maxima de pago del comprobante';
COMMENT ON COLUMN RHH.PLIS.PLISVLIS IS 'Total que cobra el IESS';
COMMENT ON COLUMN RHH.PLIS.PLISVLCT IS 'Total segun nuestra planilla de control al momento de conciliar (snapshot, no se recalcula)';
COMMENT ON COLUMN RHH.PLIS.PLISDIFR IS 'valorIess - valorControl, grabado para poder auditar que diferencia se acepto';
COMMENT ON COLUMN RHH.PLIS.PLISESTD IS '1 Registrada, 2 Conciliada, 3 Pagada, 4 Anulada';
COMMENT ON COLUMN RHH.PLIS.PLISFCPG IS 'Fecha real en que el IESS debito';
COMMENT ON COLUMN RHH.PLIS.PLISASNT IS 'Asiento del pago (CNT.ASNT); se llena al pagar';


-- =====================================================================
-- BLOQUE 2: RHH.DLIS — renglones del comprobante
-- =====================================================================
-- El total puede cuadrar y estar mal por dentro: aca vive el valor real de
-- la conciliacion.
CREATE TABLE RHH.DLIS (
    DLISCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    PLISCDGO NUMBER NOT NULL,
    DLISCNCP VARCHAR2(200) NOT NULL,
    DLISVLIS NUMBER(18,2) NOT NULL,
    DLISVLCT NUMBER(18,2),
    DLISDIFR NUMBER(18,2),
    CONSTRAINT PK_DLIS PRIMARY KEY (DLISCDGO),
    CONSTRAINT FK_DLIS_PLIS FOREIGN KEY (PLISCDGO) REFERENCES RHH.PLIS(PLISCDGO)
);

CREATE INDEX RHH.IDX_DLIS_PLIS ON RHH.DLIS(PLISCDGO);

COMMENT ON TABLE RHH.DLIS IS 'Renglones del comprobante de la planilla del IESS, con su contraparte de la planilla de control';
COMMENT ON COLUMN RHH.DLIS.DLISCNCP IS 'Texto del renglon tal como lo trae el portal';
COMMENT ON COLUMN RHH.DLIS.DLISVLIS IS 'Valor del renglon segun el IESS';
COMMENT ON COLUMN RHH.DLIS.DLISVLCT IS 'Valor equivalente segun la planilla de control; NULL si no hay control para ese tipo';
COMMENT ON COLUMN RHH.DLIS.DLISDIFR IS 'valorIess - valorControl del renglon';


