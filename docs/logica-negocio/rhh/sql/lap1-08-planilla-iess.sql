-- ---------------------------------------------------------------------
-- CONTROL 4 — el rubro y sus cuatro detalles.
-- ---------------------------------------------------------------------
SELECT r.PRBRCDGO, r.PRBRNMBR, r.PRBRALTR,
       d.PDTRCDGO, d.PDTRNMBR, d.PDTRALTR
  FROM SCP.PRBR r
  LEFT JOIN SCP.PDTR d ON d.PRBRCDGO = r.PRBRCDGO
 WHERE r.PRBRCDGO = 330
 ORDER BY d.PDTRCDGO;


