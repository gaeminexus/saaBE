-- def9-07 — D-176: cuenta de movimiento 4.8.90.90.45 PÉRDIDAS Y CONDONACIONES (hija de 4.8.90.90 OTROS) y la línea de
-- condonación de la plantilla de cobro (alterno 25, auxiliar 1 = 70, DTPL 1790 «GASTO POR CONDONACION DE PRESTAMOS»), que hoy
-- apunta a 4.1.01.30 INVERSIONES RENTA VARIABLE SECTOR NO FINANCIERO PRIVADO. 4.8.02.1 no sirve: el catálogo del B17 no
-- tiene el renglón 4802. La cuenta nueva sale en el renglón 489090 del B17 por prefijo (sin fila en CNT.CRRP, como el resto
-- de 4.8.90.90.xx). VA TAMBIÉN A PRODUCCIÓN (PASE-A-PRODUCCION.md §4).
-- Copia naturaleza, tipo y nivel de 4.8.90.90.25 (hermana de movimiento, nivel 5). Idempotente. SQL puro: correr bloque por
-- bloque; el CREATE TABLE del respaldo hace COMMIT implícito (si ya existe, ORA-00955 y se sigue); confirmar con COMMIT si
-- el control 05 da lo esperado.

-- 01 Antes: padre, hermana de referencia, la cuenta nueva (esperado: no existe) y la línea de la plantilla
SELECT PLNNCDGO, PLNNCNTA, PLNNNMBR, NTRLCDGO, PLNNTPOO, PLNNNVLL, PLNNCDPD, PLNNESTD, PJRQCDGO FROM CNT.PLNN
WHERE PJRQCDGO = 1236 AND PLNNCNTA IN ('4.8.90.90', '4.8.90.90.25', '4.8.90.90.45', '4.1.01.30') ORDER BY PLNNCNTA;
SELECT D.DTPLCDGO, D.PLNSCDGO, S.PLNSCDAL, D.DTPLAXL1, D.PLNNCDGO, N.PLNNCNTA, D.DTPLDSCR, D.DTPLESTD
FROM CNT.DTPL D JOIN CNT.PLNS S ON S.PLNSCDGO = D.PLNSCDGO JOIN CNT.PLNN N ON N.PLNNCDGO = D.PLNNCDGO
WHERE S.PLNSCDAL = 25 AND D.DTPLAXL1 = 70;

-- 02 Alta de la cuenta (no hace nada si ya existe)
INSERT INTO CNT.PLNN (PLNNCDGO, NTRLCDGO, PLNNCNTA, PLNNNMBR, PLNNTPOO, PLNNNVLL, PLNNCDPD, PLNNESTD, PLNNFCDS, PJRQCDGO, PLNNFCHA)
SELECT CNT.SQ_PLNNCDGO.NEXTVAL, H.NTRLCDGO, '4.8.90.90.45', 'PÉRDIDAS Y CONDONACIONES', H.PLNNTPOO, H.PLNNNVLL, P.PLNNCDGO, 1, NULL,
       P.PJRQCDGO, SYSDATE
FROM CNT.PLNN P
JOIN CNT.PLNN H ON H.PJRQCDGO = P.PJRQCDGO AND H.PLNNCNTA = '4.8.90.90.25'
WHERE P.PJRQCDGO = 1236 AND P.PLNNCNTA = '4.8.90.90'
  AND NOT EXISTS (SELECT 1 FROM CNT.PLNN X WHERE X.PJRQCDGO = 1236 AND X.PLNNCNTA = '4.8.90.90.45');

-- 03 Respaldo de la línea de la plantilla (una sola vez)
CREATE TABLE CNT.BKP_DTPL_D176_CONDONACION AS
SELECT D.* FROM CNT.DTPL D JOIN CNT.PLNS S ON S.PLNSCDGO = D.PLNSCDGO WHERE S.PLNSCDAL = 25 AND D.DTPLAXL1 = 70;

-- 04 La línea de condonación de la plantilla 25 apunta a la cuenta nueva
UPDATE CNT.DTPL D
SET D.PLNNCDGO = (SELECT N.PLNNCDGO FROM CNT.PLNN N WHERE N.PJRQCDGO = 1236 AND N.PLNNCNTA = '4.8.90.90.45')
WHERE D.DTPLAXL1 = 70
  AND D.PLNSCDGO IN (SELECT S.PLNSCDGO FROM CNT.PLNS S WHERE S.PLNSCDAL = 25)
  AND D.PLNNCDGO <> (SELECT N.PLNNCDGO FROM CNT.PLNN N WHERE N.PJRQCDGO = 1236 AND N.PLNNCNTA = '4.8.90.90.45');

-- 05 Después (esperado: la cuenta existe, padre 4.8.90.90, tipo y nivel como 4.8.90.90.25, activa; la línea 70 de la
--    plantilla 25 apunta a 4.8.90.90.45; el respaldo tiene la línea con su cuenta anterior)
SELECT C.PLNNCDGO, C.PLNNCNTA, C.PLNNNMBR, C.NTRLCDGO, C.PLNNTPOO, C.PLNNNVLL, P.PLNNCNTA PADRE, C.PLNNESTD, C.PJRQCDGO
FROM CNT.PLNN C JOIN CNT.PLNN P ON P.PLNNCDGO = C.PLNNCDPD WHERE C.PJRQCDGO = 1236 AND C.PLNNCNTA = '4.8.90.90.45';
SELECT D.DTPLCDGO, S.PLNSCDAL, D.DTPLAXL1, N.PLNNCNTA, N.PLNNNMBR, D.DTPLDSCR
FROM CNT.DTPL D JOIN CNT.PLNS S ON S.PLNSCDGO = D.PLNSCDGO JOIN CNT.PLNN N ON N.PLNNCDGO = D.PLNNCDGO
WHERE S.PLNSCDAL = 25 AND D.DTPLAXL1 = 70;
SELECT B.DTPLCDGO, N.PLNNCNTA CUENTA_ANTERIOR FROM CNT.BKP_DTPL_D176_CONDONACION B JOIN CNT.PLNN N ON N.PLNNCDGO = B.PLNNCDGO;
