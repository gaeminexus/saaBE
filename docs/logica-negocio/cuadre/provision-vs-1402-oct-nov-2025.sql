-- Provisión de intereses 1.4.99.05 (B17 149905) contra intereses por cobrar 1.4.02 (B17 1402), oct y nov 2025.
-- Pregunta del contador de ASOPREP (25-nov-2026) sobre el B17 de octubre: 1.160.911,72 contra 1.151.756,85.
-- Solo SELECT. Sin datos personales: préstamo = PRSTIDAS (idAsoprep).
-- Análisis en PROVISION-VS-1402-OCT-NOV-2025.md.

-- 01 saldos contables de 1.4.02 y 1.4.99.05 al 31-oct y al 30-nov
SELECT C.CORTE, SUBSTR(N.PLNNCNTA,1,9) CUENTA, ROUND(SUM(NVL(D.DTASDBEE,0)-NVL(D.DTASHBRR,0)),2) SALDO
FROM CNT.DTAS D JOIN CNT.ASNT A ON A.ASNTCDGO=D.ASNTCDGO JOIN CNT.PLNN N ON N.PLNNCDGO=D.PLNNCDGO
JOIN (SELECT DATE '2025-10-31' CORTE FROM DUAL UNION ALL SELECT DATE '2025-11-30' FROM DUAL) C ON A.ASNTFCHA < C.CORTE + 1
WHERE A.ASNTESTD<>2 AND N.PJRQCDGO=1236 AND (N.PLNNCNTA LIKE '1.4.02%' OR N.PLNNCNTA LIKE '1.4.99.05%')
GROUP BY C.CORTE, SUBSTR(N.PLNNCNTA,1,9) ORDER BY 1,2;

-- 02 libro de provisión por componente (1 interés, 2 mora) y mora contabilizada pendiente en 1.4.02
WITH c AS (SELECT DATE '2025-10-31' CORTE FROM DUAL UNION ALL SELECT DATE '2025-11-30' FROM DUAL),
pv AS (SELECT c.CORTE, ROUND(SUM(CASE WHEN m.MVICCMPN=1 THEN CASE WHEN MVICTPMV IN (1,4) THEN MVICVLOR WHEN MVICTPMV IN (2,3,9,10) THEN -MVICVLOR ELSE 0 END END),2) PROV_INTERES,
  ROUND(SUM(CASE WHEN m.MVICCMPN=2 THEN CASE WHEN MVICTPMV IN (1,4) THEN MVICVLOR WHEN MVICTPMV IN (2,3,9,10) THEN -MVICVLOR ELSE 0 END END),2) PROV_MORA
  FROM CRD.MVIC m JOIN c ON m.MVICFCCT < c.CORTE + 1 WHERE NVL(m.MVICANUL,0)=0 GROUP BY c.CORTE),
x AS (SELECT c.CORTE, CASE m.MVICTPMV WHEN 5 THEN m.MVICVLOR ELSE -m.MVICVLOR END v FROM CRD.MVIC m JOIN c ON TRUNC(m.MVICFCCT) <= c.CORTE
   WHERE m.MVICCMPN = 2 AND m.MVICTPMV IN (5, 6, 9) AND NVL(m.MVICANUL,0) = 0
  UNION ALL
  SELECT c.CORTE, -NVL(g.PGPRMRPG,0) FROM CRD.PGPR g JOIN c ON g.PGPRFCHA < c.CORTE + 1 WHERE NVL(g.PGPRANUL,0) = 0 AND g.PGPRFCHA >= DATE '2025-06-01')
SELECT pv.CORTE, pv.PROV_INTERES, pv.PROV_MORA, (SELECT ROUND(SUM(v),2) FROM x WHERE x.CORTE=pv.CORTE) MORA_PEND_1402 FROM pv ORDER BY 1;

-- 03 reverso del devengo de cuotas futuras (C27b lote 1b): lo reversado contra lo que estaba devengado
-- El SAA toma como último mes devengado el mes siguiente al ÚLTIMO cierre de cartera EJECUTADO de la base (CRD.CRCT), y en la
-- base están los cierres de producción de jul–sep 2026: reversa el interés de las cuotas hasta el 31-oct-2026. Lo correcto es
-- solo hasta el fin del mes del evento (el mes siguiente al último cierre de 2025 en el momento de la operación).
WITH r AS (
 SELECT A.ASNTCDGO, TRUNC(A.ASNTFCHA) FA, CASE WHEN D.DTASDSCR LIKE '%abono elimin%' THEN 'ABONO' ELSE 'CANCELADAS' END TIPO,
        SUBSTR(N.PLNNCNTA,1,9) CUENTA, ROUND(SUM(NVL(D.DTASHBRR,0)),2) REV
 FROM CNT.DTAS D JOIN CNT.ASNT A ON A.ASNTCDGO=D.ASNTCDGO JOIN CNT.PLNN N ON N.PLNNCDGO=D.PLNNCDGO
 WHERE A.ASNTESTD<>2 AND N.PJRQCDGO=1236 AND A.ASNTFCHA >= DATE '2025-06-01' AND A.ASNTFCHA < DATE '2026-01-01'
  AND D.DTASDSCR LIKE '%reverso del devengo del inter%' AND N.PLNNCNTA LIKE '1.4.02%'
 GROUP BY A.ASNTCDGO, TRUNC(A.ASNTFCHA), CASE WHEN D.DTASDSCR LIKE '%abono elimin%' THEN 'ABONO' ELSE 'CANCELADAS' END, SUBSTR(N.PLNNCNTA,1,9)),
-- préstamo y evento: por el evento que guarda el asiento (EVPRNMAS) o, en los cobros por ventanilla, por el detalle del cobro
-- (CBCR.CBCRASN1/ASN2 → DCBC con evento): un renglón por préstamo del asiento
ev AS (SELECT v.EVPRNMAS ASNTCDGO, v.PRSTCDGO, v.EVPRCDGO, TRUNC(v.EVPRFCHA) FE FROM CRD.EVPR v
  UNION
  SELECT NVL(b.CBCRASN2, b.CBCRASN1), dc.PRSTCDGO, dc.EVPRCDGO, TRUNC(v.EVPRFCHA) FROM CRD.CBCR b JOIN CRD.DCBC dc ON dc.CBCRCDGO=b.CBCRCDGO
   JOIN CRD.EVPR v ON v.EVPRCDGO=dc.EVPRCDGO
   WHERE NOT EXISTS (SELECT 1 FROM CRD.EVPR w WHERE w.EVPRNMAS=NVL(b.CBCRASN2, b.CBCRASN1))),
e AS (SELECT r.*, ev.PRSTCDGO, ev.EVPRCDGO, NVL(ev.FE, r.FA) FE FROM r
  LEFT JOIN ev ON ev.ASNTCDGO=r.ASNTCDGO AND ev.PRSTCDGO = (SELECT MIN(e2.PRSTCDGO) FROM ev e2 WHERE e2.ASNTCDGO=r.ASNTCDGO
    AND (r.TIPO = 'ABONO' AND EXISTS (SELECT 1 FROM CRD.HDTP h2 WHERE h2.EVPRCDGO=e2.EVPRCDGO)
      OR r.TIPO = 'CANCELADAS' AND EXISTS (SELECT 1 FROM CRD.DTPR d2 WHERE d2.PRSTCDGO=e2.PRSTCDGO AND d2.DTPRESTD=7 AND d2.DTPRFCVN > e2.FE)))),
pg AS (SELECT g.DTPRCDGO, SUM(NVL(g.PGPRINPG,0)) IP FROM CRD.PGPR g WHERE NVL(g.PGPRANUL,0)=0 GROUP BY g.DTPRCDGO),
cn AS (SELECT e.ASNTCDGO,
  SUM(CASE WHEN d.DTPRFCVN > e.FE AND d.DTPRFCVN <= LAST_DAY(e.FE) THEN GREATEST(NVL(d.DTPRINTR,0)-NVL(pg.IP,0),0) ELSE 0 END) CORRECTO,
  SUM(CASE WHEN d.DTPRFCVN > e.FE AND d.DTPRFCVN <= DATE '2026-10-31' THEN GREATEST(NVL(d.DTPRINTR,0)-NVL(pg.IP,0),0) ELSE 0 END) EMULADO
  FROM e JOIN CRD.DTPR d ON d.PRSTCDGO=e.PRSTCDGO AND d.DTPRESTD=7 LEFT JOIN pg ON pg.DTPRCDGO=d.DTPRCDGO
  WHERE e.TIPO='CANCELADAS' GROUP BY e.ASNTCDGO),
ab AS (SELECT e.ASNTCDGO,
  SUM(CASE WHEN h.DTPRFCVN >= DATE '2025-10-01' AND h.DTPRFCVN <= LAST_DAY(e.FE) THEN NVL(h.DTPRINTR,0) - NVL(d.DTPRINTR,0) ELSE 0 END) CORRECTO,
  SUM(CASE WHEN h.DTPRFCVN >= DATE '2025-10-01' AND h.DTPRFCVN <= DATE '2026-10-31' THEN NVL(h.DTPRINTR,0) - NVL(d.DTPRINTR,0) ELSE 0 END) EMULADO
  FROM e JOIN CRD.HDTP h ON h.EVPRCDGO=e.EVPRCDGO LEFT JOIN CRD.DTPR d ON d.DTPRCDGO=h.DTPRCDGO
  WHERE e.TIPO='ABONO' GROUP BY e.ASNTCDGO)
SELECT TO_CHAR(e.FA,'YYYY-MM') MES, e.TIPO, e.CUENTA, COUNT(*) ASIENTOS, SUM(CASE WHEN e.PRSTCDGO IS NULL THEN 1 ELSE 0 END) SIN_PRESTAMO,
  ROUND(SUM(e.REV),2) REVERSADO, ROUND(SUM(NVL(cn.CORRECTO, ab.CORRECTO)),2) CORRECTO, ROUND(SUM(NVL(cn.EMULADO, ab.EMULADO)),2) EMULADO_HASTA_OCT26,
  ROUND(SUM(e.REV) - SUM(NVL(NVL(cn.CORRECTO, ab.CORRECTO),0)),2) EXCESO
FROM e LEFT JOIN cn ON cn.ASNTCDGO=e.ASNTCDGO LEFT JOIN ab ON ab.ASNTCDGO=e.ASNTCDGO
GROUP BY TO_CHAR(e.FA,'YYYY-MM'), e.TIPO, e.CUENTA ORDER BY 1,2,3;

-- 04 cierres de cartera EJECUTADOS en la base (el último fija el límite del reverso)
SELECT CRCTCDGO, TO_CHAR(CRCTFCCR,'YYYY-MM-DD') CORTE, CRCTIDST EST, TO_CHAR(CRCTFCRG,'YYYY-MM-DD') REGISTRO FROM CRD.CRCT WHERE CRCTFCCR >= DATE '2025-09-01' ORDER BY CRCTFCCR, CRCTCDGO;

-- 05 provisión de interés vigente sobre cuotas que al corte ya no están pendientes (canceladas o pagadas antes del corte)
WITH c AS (SELECT DATE '2025-10-31' CORTE FROM DUAL UNION ALL SELECT DATE '2025-11-30' FROM DUAL),
pv AS (SELECT c.CORTE, m.DTPRCDGO, SUM(CASE WHEN MVICTPMV IN (1,4) THEN MVICVLOR WHEN MVICTPMV IN (2,3,9,10) THEN -MVICVLOR ELSE 0 END) PROV
  FROM CRD.MVIC m JOIN c ON m.MVICFCCT < c.CORTE+1 WHERE NVL(m.MVICANUL,0)=0 AND m.MVICCMPN=1 GROUP BY c.CORTE, m.DTPRCDGO)
SELECT pv.CORTE, d.DTPRESTD EST_CUOTA, COUNT(*) CUOTAS, COUNT(DISTINCT d.PRSTCDGO) PRESTAMOS, ROUND(SUM(pv.PROV),2) PROV_INTERES
FROM pv JOIN CRD.DTPR d ON d.DTPRCDGO=pv.DTPRCDGO
WHERE ABS(pv.PROV) > 0.004 AND d.DTPRESTD IN (4,7) AND d.DTPRFCPG < pv.CORTE + 1
GROUP BY pv.CORTE, d.DTPRESTD ORDER BY 1,2;

-- 06 paso ⑦: asiento contra libro (MVIC tipo 1 del mismo asiento)
SELECT m.ASNTCDGO, TO_CHAR(MIN(m.MVICFCCT),'YYYY-MM-DD') CORTE,
  ROUND(SUM(CASE WHEN m.MVICCMPN=1 THEN m.MVICVLOR END),2) LIBRO_INTERES, ROUND(SUM(CASE WHEN m.MVICCMPN=2 THEN m.MVICVLOR END),2) LIBRO_MORA,
  (SELECT ROUND(SUM(NVL(D.DTASHBRR,0)-NVL(D.DTASDBEE,0)),2) FROM CNT.DTAS D JOIN CNT.PLNN N ON N.PLNNCDGO=D.PLNNCDGO WHERE D.ASNTCDGO=m.ASNTCDGO AND N.PLNNCNTA LIKE '1.4.99.05%') ASIENTO
FROM CRD.MVIC m WHERE m.MVICORGN='CIERRE' AND m.MVICTPMV=1 AND NVL(m.MVICANUL,0)=0 AND m.MVICFCCT >= DATE '2025-06-01' AND m.MVICFCCT < DATE '2025-12-01'
GROUP BY m.ASNTCDGO ORDER BY 2;
