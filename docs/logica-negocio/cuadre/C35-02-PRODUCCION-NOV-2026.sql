-- C35-02 para PRODUCCIÓN, antes del cierre de cartera de noviembre 2026 (pedido del árbitro omen-saa-1, 25-nov-2026).
-- La previsualización de noviembre 2026 con el EAR cierre-1125-d187 bloquea la ejecución porque 7 cuotas tienen DTPRSLOT
-- (saldo «otros») sin pagos que lo respalden: 38.401,75 en total, en las operaciones 70607, 71053, 68669, 67023, 70549, 63417 y 63031 (PRSTIDAS).
-- Es el mismo defecto de la cartera migrada que en el re-proceso (D-141 (2), C35) y el mismo mecanismo de
-- 03-trabajo/cambios-saa/c35-abono-cruce/sql/C35-02 y de def9-05 (septiembre 2025): DTPRSLOT = lo respaldado por los PGPR vigentes,
-- con rastro en CRD.HDTP (motivo SLOT_SIN_RESPALDO_C35). Solo cambia DTPRSLOT: la 1.3 y la G48 leen los PGPR.
-- SQL puro (cliente JDBC, bloque por bloque). El CREATE TABLE del bloque 00 hace COMMIT implícito. El bloque 02 se detiene
-- (ORA-20813) si no encuentra exactamente 7 cuotas y 38.401,75. Si da otra cifra, NO seguir: mandar la salida del bloque 01.
-- Después del bloque 03 correcto: COMMIT. Vuelta atrás: restaurar DTPRSLOT desde CRD.BKP_DTPR_C35_SLOT_PROD_202611.

-- 00 Respaldo de las cuotas con DTPRSLOT sin respaldo de esas 7 operaciones
CREATE TABLE CRD.BKP_DTPR_C35_SLOT_PROD_202611 AS
WITH PG AS (SELECT DTPRCDGO, ROUND(SUM(NVL(PGPRSLOT,0)),2) S FROM CRD.PGPR WHERE NVL(PGPRANUL,0) = 0 GROUP BY DTPRCDGO)
SELECT d.*, NVL(pg.S,0) C35_RESPALDADO, ROUND(d.DTPRSLOT - NVL(pg.S,0),2) C35_RESIDUO, p.PRSTIDAS C35_OPERACION,
       p.PRSTIDST C35_ESTADO_PRESTAMO, SYSTIMESTAMP C35_FECHA_RESPALDO
  FROM CRD.DTPR d JOIN CRD.PRST p ON p.PRSTCDGO = d.PRSTCDGO LEFT JOIN PG pg ON pg.DTPRCDGO = d.DTPRCDGO
 WHERE TRIM(p.PRSTIDAS) IN ('70607','71053','68669','67023','70549','63417','63031')
   AND d.DTPRSLOT - NVL(pg.S,0) > 0.01;

-- 01 Control del respaldo. Esperado: 7 cuotas, residuo 38.401,75.
SELECT C35_OPERACION, DTPRNMCT CUOTA, DTPRESTD, DTPRSLOT, C35_RESPALDADO, C35_RESIDUO FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611 ORDER BY C35_OPERACION, DTPRNMCT;
SELECT COUNT(*) CUOTAS, ROUND(SUM(C35_RESIDUO),2) RESIDUO FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611;

-- 02 Rastro en HDTP y corrección con guardias
DECLARE
  v NUMBER;
  PROCEDURE g(p_que VARCHAR2, p_n NUMBER, p_esp NUMBER) IS
  BEGIN
    IF p_n <> p_esp THEN RAISE_APPLICATION_ERROR(-20813, p_que || ': ' || p_n || ', esperado ' || p_esp); END IF;
  END;
BEGIN
  SELECT COUNT(*) INTO v FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611; g('RESPALDO', v, 7);
  SELECT ROUND(SUM(C35_RESIDUO),2) INTO v FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611; g('RESIDUO', v, 38401.75);
  INSERT INTO CRD.HDTP (DTPRCDGO, EVPRCDGO, HDTPMTVO, HDTPFCRG, HDTPUSAR,
         PRSTCDGO, DTPRNMCT, DTPRFCVN, DTPRCPTL, DTPRINTR, DTPRMRAA, DTPRINVN, DTPRSLCP, DTPRSLIN, DTPRSLMR, DTPRSLIV,
         DTPRFCPG, DTPRABNO, DTPRCPPG, DTPRINPG, DTPRDSGR, DTPRCTAA, DTPRSLDO, DTPRSLOT, DTPRDSFR, DTPRDSDF, DTPRDSOR,
         DTPRVLDF, DTPRTTLL, DTPRMRPG, DTPRDSPG, DTPRINVP, DTPRMRCL, DTPRDSMR, DTPRESTD, DTPRFCRG, DTPRUSRG, DTPRIDST,
         DTPRCDEX, DTPROTSG, DTPRTTCS, DTPRVLSI, DTPRSICP)
  SELECT b.DTPRCDGO, NULL, 'SLOT_SIN_RESPALDO_C35', SYSTIMESTAMP, 'C35PROD',
         b.PRSTCDGO, b.DTPRNMCT, b.DTPRFCVN, b.DTPRCPTL, b.DTPRINTR, b.DTPRMRAA, b.DTPRINVN, b.DTPRSLCP, b.DTPRSLIN,
         b.DTPRSLMR, b.DTPRSLIV, b.DTPRFCPG, b.DTPRABNO, b.DTPRCPPG, b.DTPRINPG, b.DTPRDSGR, b.DTPRCTAA, b.DTPRSLDO,
         b.DTPRSLOT, b.DTPRDSFR, b.DTPRDSDF, b.DTPRDSOR, b.DTPRVLDF, b.DTPRTTLL, b.DTPRMRPG, b.DTPRDSPG, b.DTPRINVP,
         b.DTPRMRCL, b.DTPRDSMR, b.DTPRESTD, b.DTPRFCRG, b.DTPRUSRG, b.DTPRIDST, b.DTPRCDEX, b.DTPROTSG, b.DTPRTTCS,
         b.DTPRVLSI, b.DTPRSICP
    FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611 b;
  g('HDTP', SQL%ROWCOUNT, 7);
  UPDATE CRD.DTPR d
     SET d.DTPRSLOT = (SELECT b.C35_RESPALDADO FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611 b WHERE b.DTPRCDGO = d.DTPRCDGO)
   WHERE d.DTPRCDGO IN (SELECT b.DTPRCDGO FROM CRD.BKP_DTPR_C35_SLOT_PROD_202611 b WHERE b.DTPRSLOT = d.DTPRSLOT);
  g('DTPRSLOT_CORREGIDAS', SQL%ROWCOUNT, 7);
END;
/

-- 03 Después. Esperado: las 7 cuotas con DTPRSLOT = respaldado; luego COMMIT y volver a previsualizar el cierre.
WITH PG AS (SELECT DTPRCDGO, ROUND(SUM(NVL(PGPRSLOT,0)),2) S FROM CRD.PGPR WHERE NVL(PGPRANUL,0) = 0 GROUP BY DTPRCDGO)
SELECT b.C35_OPERACION, d.DTPRNMCT, d.DTPRESTD, d.DTPRSLOT, NVL(pg.S,0) RESPALDADO, d.DTPRSLDO
  FROM CRD.DTPR d JOIN CRD.BKP_DTPR_C35_SLOT_PROD_202611 b ON b.DTPRCDGO = d.DTPRCDGO LEFT JOIN PG pg ON pg.DTPRCDGO = d.DTPRCDGO
 ORDER BY b.C35_OPERACION, d.DTPRNMCT;
