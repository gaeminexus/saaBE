-- C11 (cuadre Superintendencia): catalogo de centros de costo de ASOPREP (empresa 1236) en CNT.CNCS.
-- Decision D-005 (28-oct-2026): arbol  ASOPREP  >  01 ASOPREP ADMINISTRACION  |  02 ASOPREP ARRIENDOS.
-- Numeracion con la convencion del propio modulo (CentroCostoServiceImpl.saveCuenta / CuentaServiceImpl.obtieneCuentaPadre):
--   raiz "0" (nivel 0, idPadre 0, ACUMULACION, la crea creaNodoArbolCero), "1" ASOPREP (nivel 1, ACUMULACION),
--   "1.01" y "1.02" (nivel 2, MOVIMIENTO). El cargador historico y el cargador de asientos manuales (C5) referencian
--   el centro por CNCSNMRO: el Excel "01 ASOPREP ADMINISTRACION" -> 1.01, "02 ASOPREP ARRIENDOS" -> 1.02.
-- Columnas (entidad CentroCosto): CNCSCDGO (CNT.SQ_CNCSCDGO), CNCSNMBR, CNCSNMRO, CNCSTPOO (1 acumulacion / 2 movimiento),
--   CNCSNVLL, CNCSCDPD (id del padre), CNCSESTD (1 activo), PJRQCDGO, CNCSFCHA (fecha de ingreso).
-- SQL puro, sin COMMIT: lo da quien lo corre despues de revisar el control posterior. Idempotente: cada INSERT
-- se salta si ya existe el numero para la empresa.

-- 1 Control previo: hoy la empresa 1236 no tiene centros (inventario del 28-oct-2026: 0 filas)
SELECT CNCSCDGO, CNCSNMRO, CNCSNMBR, CNCSTPOO, CNCSNVLL, CNCSCDPD, CNCSESTD
FROM CNT.CNCS WHERE PJRQCDGO = 1236 ORDER BY CNCSNMRO;

-- 2 Raiz del arbol (igual que creaNodoArbolCero)
INSERT INTO CNT.CNCS (CNCSCDGO, CNCSNMBR, CNCSNMRO, CNCSTPOO, CNCSNVLL, CNCSCDPD, CNCSESTD, PJRQCDGO, CNCSFCHA)
SELECT CNT.SQ_CNCSCDGO.NEXTVAL, 'CENTRO COSTO', '0', 1, 0, 0, 1, 1236, SYSDATE FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '0');

-- 3 Nivel 1: ASOPREP (acumulacion, hijo de la raiz)
INSERT INTO CNT.CNCS (CNCSCDGO, CNCSNMBR, CNCSNMRO, CNCSTPOO, CNCSNVLL, CNCSCDPD, CNCSESTD, PJRQCDGO, CNCSFCHA)
SELECT CNT.SQ_CNCSCDGO.NEXTVAL, 'ASOPREP', '1', 1, 1,
       (SELECT CNCSCDGO FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '0'), 1, 1236, SYSDATE FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '1');

-- 4 Nivel 2: los dos centros de movimiento que trae el control del contador
INSERT INTO CNT.CNCS (CNCSCDGO, CNCSNMBR, CNCSNMRO, CNCSTPOO, CNCSNVLL, CNCSCDPD, CNCSESTD, PJRQCDGO, CNCSFCHA)
SELECT CNT.SQ_CNCSCDGO.NEXTVAL, '01 ASOPREP ADMINISTRACION', '1.01', 2, 2,
       (SELECT CNCSCDGO FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '1'), 1, 1236, SYSDATE FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '1.01');

INSERT INTO CNT.CNCS (CNCSCDGO, CNCSNMBR, CNCSNMRO, CNCSTPOO, CNCSNVLL, CNCSCDPD, CNCSESTD, PJRQCDGO, CNCSFCHA)
SELECT CNT.SQ_CNCSCDGO.NEXTVAL, '02 ASOPREP ARRIENDOS', '1.02', 2, 2,
       (SELECT CNCSCDGO FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '1'), 1, 1236, SYSDATE FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM CNT.CNCS WHERE PJRQCDGO = 1236 AND CNCSNMRO = '1.02');

-- 5 Control posterior: se esperan 4 filas (0, 1, 1.01, 1.02); 1.01 y 1.02 con CNCSTPOO = 2 y CNCSCDPD = id de '1'
SELECT c.CNCSCDGO, c.CNCSNMRO, c.CNCSNMBR, c.CNCSTPOO, c.CNCSNVLL, c.CNCSCDPD, p.CNCSNMRO padre, c.CNCSESTD
FROM CNT.CNCS c LEFT JOIN CNT.CNCS p ON p.CNCSCDGO = c.CNCSCDPD
WHERE c.PJRQCDGO = 1236 ORDER BY c.CNCSNMRO;

