-- =====================================================
-- 2. CNT.LNNV — línea por justificar
-- =====================================================
CREATE TABLE CNT.LNNV (
    LNNVCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    NVDDCDGO NUMBER NOT NULL,
    LNNVSCNC NUMBER NOT NULL,
    LNNVORGN VARCHAR2(20) NOT NULL,
    ASNTCDGO NUMBER,
    DTASCDGO NUMBER,
    DTASCDPR NUMBER,
    PLNNCDGO NUMBER NOT NULL,
    LNNVFCHA DATE,
    LNNVDSCR VARCHAR2(1000),
    LNNVVLOR NUMBER(18,2) NOT NULL,
    LNNVSNTD CHAR(1) NOT NULL,
    LNNVTPRF VARCHAR2(20),
    LNNVRFRN VARCHAR2(100),
    DEXBCDGO NUMBER,
    PRSTCDGO NUMBER,
    ENTDCDGO NUMBER,
    LNNVSLDO NUMBER(18,2) NOT NULL,
    LNNVESTD NUMBER DEFAULT 1 NOT NULL,
    LNNVFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    LNNVUSAR VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_LNNV PRIMARY KEY (LNNVCDGO),
    CONSTRAINT FK_LNNV_NVDD FOREIGN KEY (NVDDCDGO) REFERENCES CNT.NVDD(NVDDCDGO),
    CONSTRAINT FK_LNNV_ASNT FOREIGN KEY (ASNTCDGO) REFERENCES CNT.ASNT(ASNTCDGO),
    CONSTRAINT FK_LNNV_DTAS FOREIGN KEY (DTASCDGO) REFERENCES CNT.DTAS(DTASCDGO),
    CONSTRAINT FK_LNNV_DTPR FOREIGN KEY (DTASCDPR) REFERENCES CNT.DTAS(DTASCDGO),
    CONSTRAINT FK_LNNV_PLNN FOREIGN KEY (PLNNCDGO) REFERENCES CNT.PLNN(PLNNCDGO),
    CONSTRAINT CK_LNNV_ORGN CHECK (LNNVORGN IN ('CONTRAPARTIDA', 'LINEA_PR', 'MANUAL', 'DESGLOSE')),
    CONSTRAINT CK_LNNV_ORIGEN CHECK (LNNVORGN = 'MANUAL' OR (LNNVORGN = 'DESGLOSE' AND ASNTCDGO IS NOT NULL AND DTASCDPR IS NOT NULL)
        OR (ASNTCDGO IS NOT NULL AND DTASCDGO IS NOT NULL AND DTASCDPR IS NOT NULL)),
    CONSTRAINT CK_LNNV_VLOR CHECK (LNNVVLOR > 0),
    CONSTRAINT CK_LNNV_SNTD CHECK (LNNVSNTD IN ('D', 'H')),
    CONSTRAINT CK_LNNV_SLDO CHECK (LNNVSLDO >= 0 AND LNNVSLDO <= LNNVVLOR),
    CONSTRAINT CK_LNNV_ESTD CHECK (LNNVESTD IN (1, 2, 3, 4))
);

CREATE INDEX IDX_LNNV_NVDD ON CNT.LNNV(NVDDCDGO);
CREATE INDEX IDX_LNNV_ASNT ON CNT.LNNV(ASNTCDGO);
CREATE INDEX IDX_LNNV_DTAS ON CNT.LNNV(DTASCDGO);
CREATE INDEX IDX_LNNV_DTPR ON CNT.LNNV(DTASCDPR);
CREATE INDEX IDX_LNNV_PLNN ON CNT.LNNV(PLNNCDGO);
CREATE INDEX IDX_LNNV_DEXB ON CNT.LNNV(DEXBCDGO);
CREATE INDEX IDX_LNNV_PRST ON CNT.LNNV(PRSTCDGO);
CREATE INDEX IDX_LNNV_ENTD ON CNT.LNNV(ENTDCDGO);
-- Una línea de asiento no se repite en la misma novedad (idempotencia de C34-02); las MANUAL quedan fuera.
CREATE UNIQUE INDEX UK_LNNV_DTAS ON CNT.LNNV(CASE WHEN DTASCDGO IS NOT NULL THEN NVDDCDGO END, DTASCDGO);

COMMENT ON TABLE CNT.LNNV IS 'C34: línea por justificar de una novedad (movimiento que pasó por una cuenta por regularizar)';
COMMENT ON COLUMN CNT.LNNV.LNNVORGN IS 'CONTRAPARTIDA: la línea del movimiento (banco, cobro) de un asiento con una sola línea por regularizar; LINEA_PR: la línea de la cuenta por regularizar; DESGLOSE: una fila de origen (p. ej. un aporte de un partícipe) de una línea agregada, que queda ANULADA; MANUAL: agregada a mano';
COMMENT ON COLUMN CNT.LNNV.DTASCDGO IS 'Línea del asiento que se muestra (la contrapartida o la de la cuenta por regularizar)';
COMMENT ON COLUMN CNT.LNNV.DTASCDPR IS 'Línea del asiento en la cuenta por regularizar afectada';
COMMENT ON COLUMN CNT.LNNV.PLNNCDGO IS 'Cuenta por regularizar afectada';
COMMENT ON COLUMN CNT.LNNV.LNNVVLOR IS 'Valor de la línea (positivo)';
COMMENT ON COLUMN CNT.LNNV.LNNVSNTD IS 'Sentido sobre la cuenta afectada: D débito (salida sin respaldo), H crédito (depósito por confirmar)';
COMMENT ON COLUMN CNT.LNNV.DEXBCDGO IS 'Fila del extracto bancario (TSR.DEXB), sin FK';
COMMENT ON COLUMN CNT.LNNV.PRSTCDGO IS 'Préstamo (CRD.PRST), sin FK';
COMMENT ON COLUMN CNT.LNNV.ENTDCDGO IS 'Partícipe (CRD.ENTD), sin FK';
COMMENT ON COLUMN CNT.LNNV.LNNVSLDO IS 'Saldo por justificar = valor - suma de justificaciones vigentes (lo mantiene el servicio)';
COMMENT ON COLUMN CNT.LNNV.LNNVESTD IS '1 PENDIENTE, 2 PARCIAL, 3 JUSTIFICADA, 4 ANULADA';


-- =====================================================
-- 3. CNT.JSNV — justificación de una línea
-- =====================================================
CREATE TABLE CNT.JSNV (
    JSNVCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    LNNVCDGO NUMBER NOT NULL,
    NVDDCDGO NUMBER NOT NULL,
    JSNVMNTO NUMBER(18,2) NOT NULL,
    JSNVTPJS VARCHAR2(20) NOT NULL,
    LNNVCRUC NUMBER,
    JSNVFCHH DATE,
    JSNVTPDC VARCHAR2(30),
    JSNVNMDC VARCHAR2(100),
    DCSNCDGO NUMBER,
    JSNVTXTO VARCHAR2(4000),
    JSNVESTD NUMBER DEFAULT 1 NOT NULL,
    JSNVFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    JSNVUSAR VARCHAR2(50) NOT NULL,
    JSNVFCAN TIMESTAMP,
    JSNVUSAN VARCHAR2(50),
    JSNVMTAN VARCHAR2(1000),
    CONSTRAINT PK_JSNV PRIMARY KEY (JSNVCDGO),
    CONSTRAINT FK_JSNV_LNNV FOREIGN KEY (LNNVCDGO) REFERENCES CNT.LNNV(LNNVCDGO),
    CONSTRAINT FK_JSNV_NVDD FOREIGN KEY (NVDDCDGO) REFERENCES CNT.NVDD(NVDDCDGO),
    CONSTRAINT FK_JSNV_CRUC FOREIGN KEY (LNNVCRUC) REFERENCES CNT.LNNV(LNNVCDGO),
    CONSTRAINT FK_JSNV_DCSN FOREIGN KEY (DCSNCDGO) REFERENCES CNT.DCSN(DCSNCDGO),
    CONSTRAINT CK_JSNV_MNTO CHECK (JSNVMNTO > 0),
    CONSTRAINT CK_JSNV_TPJS CHECK (JSNVTPJS IN ('RESPALDO', 'DECISION', 'CRUCE')),
    CONSTRAINT CK_JSNV_TIPO CHECK ((JSNVTPJS = 'DECISION' AND DCSNCDGO IS NOT NULL)
        OR (JSNVTPJS = 'CRUCE' AND LNNVCRUC IS NOT NULL) OR JSNVTPJS = 'RESPALDO'),
    CONSTRAINT CK_JSNV_ESTD CHECK (JSNVESTD IN (1, 2)),
    CONSTRAINT CK_JSNV_ANULA CHECK (JSNVESTD = 1 OR (JSNVFCAN IS NOT NULL AND JSNVUSAN IS NOT NULL AND JSNVMTAN IS NOT NULL))
);

CREATE INDEX IDX_JSNV_LNNV ON CNT.JSNV(LNNVCDGO);
CREATE INDEX IDX_JSNV_NVDD ON CNT.JSNV(NVDDCDGO);
CREATE INDEX IDX_JSNV_CRUC ON CNT.JSNV(LNNVCRUC);
CREATE INDEX IDX_JSNV_DCSN ON CNT.JSNV(DCSNCDGO);

COMMENT ON TABLE CNT.JSNV IS 'C34: justificación (total o parcial) de una línea por justificar; sin cuatro ojos, se anula con motivo';
COMMENT ON COLUMN CNT.JSNV.JSNVTPJS IS 'RESPALDO (documento), DECISION (de ASOPREP, exige DCSNCDGO), CRUCE (con otra línea de signo contrario, LNNVCRUC)';
COMMENT ON COLUMN CNT.JSNV.JSNVFCHH IS 'Fecha del hecho según el respaldo';
COMMENT ON COLUMN CNT.JSNV.JSNVTPDC IS 'Tipo de documento de respaldo (comprobante de egreso, transferencia, factura...)';
COMMENT ON COLUMN CNT.JSNV.JSNVNMDC IS 'Número del documento de respaldo';
COMMENT ON COLUMN CNT.JSNV.JSNVESTD IS '1 VIGENTE, 2 ANULADA';


