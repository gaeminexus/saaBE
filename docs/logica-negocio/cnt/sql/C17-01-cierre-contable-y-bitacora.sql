-- BLOQUE 2 — DDL
ALTER TABLE CNT.PRDO ADD (
  PRDOCNCR NUMBER(1),
  PRDOFCCN TIMESTAMP(6),
  PRDOUSCN VARCHAR2(100)
);

COMMENT ON COLUMN CNT.PRDO.PRDOCNCR IS 'C17: 1 = periodo cerrado para contabilidad (no admite asientos de ningun modulo); 0/NULL = abierto';
COMMENT ON COLUMN CNT.PRDO.PRDOFCCN IS 'C17: fecha y hora del cierre contable vigente';
COMMENT ON COLUMN CNT.PRDO.PRDOUSCN IS 'C17: usuario que cerro el periodo';

CREATE TABLE CNT.HCPR (
  HCPRCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY,
  PJRQCDGO NUMBER,
  HCPRANNO NUMBER(4)      NOT NULL,
  HCPRMESS NUMBER(2)      NOT NULL,
  HCPRTPOO VARCHAR2(10)   NOT NULL,
  HCPRACCN VARCHAR2(12)   NOT NULL,
  HCPRFCHA TIMESTAMP(6)   NOT NULL,
  HCPRUSRO VARCHAR2(100)  NOT NULL,
  HCPRIPPP VARCHAR2(50),
  HCPRMTVO VARCHAR2(1000),
  PRDOCDGO NUMBER,
  CRCTCDGO NUMBER,
  HCPRFRDN NUMBER(1),
  CONSTRAINT PK_HCPR PRIMARY KEY (HCPRCDGO),
  CONSTRAINT CK_HCPR_TIPO CHECK (HCPRTPOO IN ('CONTABLE', 'CARTERA')),
  CONSTRAINT CK_HCPR_ACCION CHECK (HCPRACCN IN ('CIERRE', 'REAPERTURA'))
);

COMMENT ON TABLE CNT.HCPR IS 'C17: bitacora de cierres y reaperturas de periodo (contable y cartera). Solo INSERT.';
COMMENT ON COLUMN CNT.HCPR.HCPRFRDN IS '1 = hecho fuera de orden con -Dsaa.cierres.permitirFueraDeOrden=true';

CREATE INDEX IX_HCPR_PERIODO ON CNT.HCPR (PJRQCDGO, HCPRANNO, HCPRMESS, HCPRTPOO);

