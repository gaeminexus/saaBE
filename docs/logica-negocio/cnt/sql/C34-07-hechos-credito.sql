-- BLOQUE 5 — CONTROLES DESPUÉS
-- 5.1 Tablas nuevas. ESPERADO: HCNV 16 columnas, OHNV 14.
SELECT TABLE_NAME, COUNT(*) COLUMNAS FROM ALL_TAB_COLUMNS WHERE OWNER = 'CNT' AND TABLE_NAME IN ('HCNV', 'OHNV') GROUP BY TABLE_NAME ORDER BY 1;
-- 5.2 HCNVCDGO en JSNV, RSNV y ADNV. ESPERADO: 3 filas.
SELECT TABLE_NAME FROM ALL_TAB_COLUMNS WHERE OWNER = 'CNT' AND COLUMN_NAME = 'HCNVCDGO' AND TABLE_NAME IN ('JSNV', 'RSNV', 'ADNV') ORDER BY 1;
-- 5.3 Reglas. ESPERADO: todas ENABLED / VALIDATED; CK_JSNV_TPJS con HECHO, CK_ADNV_DUENO con HCNVCDGO, CK_HSNV_ACCN con HECHO_CREDITO.
--     (Sin las NOT NULL. HCNV: PK + 4 CK; OHNV: PK, 2 FK y 4 CK; más las 7 nombradas.)
SELECT TABLE_NAME, CONSTRAINT_NAME, STATUS, VALIDATED FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CNT'
   AND (TABLE_NAME IN ('HCNV', 'OHNV')
        OR CONSTRAINT_NAME IN ('CK_JSNV_TPJS', 'CK_JSNV_TIPO', 'CK_ADNV_DUENO', 'CK_HSNV_ACCN', 'FK_JSNV_HCNV', 'FK_RSNV_HCNV', 'FK_ADNV_HCNV'))
   AND (CONSTRAINT_TYPE <> 'C' OR SEARCH_CONDITION_VC NOT LIKE '%IS NOT NULL')
 ORDER BY 1, 2;


