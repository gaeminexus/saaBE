-- =====================================================
-- 2. CNT.HCNV — hecho de crédito
-- =====================================================
CREATE TABLE CNT.HCNV (
    HCNVCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    PJRQCDGO NUMBER NOT NULL,
    PRSTCDGO NUMBER NOT NULL,
    HCNVTIPO VARCHAR2(20) NOT NULL,
    HCNVFCHA DATE NOT NULL,
    HCNVVLOR NUMBER(18,2) NOT NULL,
    DTPRCDGO NUMBER,
    HCNVTXTO VARCHAR2(4000),
    HCNVTPDC VARCHAR2(30),
    HCNVNMDC VARCHAR2(100),
    HCNVESTD NUMBER DEFAULT 1 NOT NULL,
    HCNVFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    HCNVUSAR VARCHAR2(50) NOT NULL,
    HCNVFCAN TIMESTAMP,
    HCNVUSAN VARCHAR2(50),
    HCNVMTAN VARCHAR2(1000),
    CONSTRAINT PK_HCNV PRIMARY KEY (HCNVCDGO),
    CONSTRAINT CK_HCNV_TIPO CHECK (HCNVTIPO IN ('ABONO_CAPITAL', 'PAGO_CUOTAS', 'PRECANCELACION', 'REAPERTURA_CUOTAS', 'PARTICIPE_DEBE')),
    CONSTRAINT CK_HCNV_VLOR CHECK (HCNVVLOR > 0),
    CONSTRAINT CK_HCNV_ESTD CHECK (HCNVESTD IN (1, 2)),
    CONSTRAINT CK_HCNV_ANULA CHECK (HCNVESTD = 1 OR (HCNVFCAN IS NOT NULL AND HCNVUSAN IS NOT NULL AND HCNVMTAN IS NOT NULL))
);

CREATE INDEX IDX_HCNV_PRST ON CNT.HCNV(PRSTCDGO);
CREATE INDEX IDX_HCNV_PJRQ ON CNT.HCNV(PJRQCDGO);

COMMENT ON TABLE CNT.HCNV IS 'C34d: hecho de crédito con que Crédito resuelve novedades; lo aplica la pasada v8 con el motor de crédito en su mes';
COMMENT ON COLUMN CNT.HCNV.PRSTCDGO IS 'Operación (CRD.PRST), sin FK';
COMMENT ON COLUMN CNT.HCNV.HCNVTIPO IS 'ABONO_CAPITAL, PAGO_CUOTAS, PRECANCELACION, REAPERTURA_CUOTAS, PARTICIPE_DEBE';
COMMENT ON COLUMN CNT.HCNV.HCNVFCHA IS 'Fecha real del hecho (la v8 lo aplica en ese mes)';
COMMENT ON COLUMN CNT.HCNV.DTPRCDGO IS 'Cuota (CRD.DTPR) desde la que se recalcula la tabla, sin FK';
COMMENT ON COLUMN CNT.HCNV.HCNVESTD IS '1 VIGENTE, 2 ANULADO';


-- =====================================================
-- 3. CNT.OHNV — origen del dinero de un hecho
-- =====================================================
CREATE TABLE CNT.OHNV (
    OHNVCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    HCNVCDGO NUMBER NOT NULL,
    OHNVTIPO VARCHAR2(20) NOT NULL,
    DEXBCDGO NUMBER,
    APRTCDGO NUMBER,
    LNNVCDGO NUMBER,
    OHNVVLOR NUMBER(18,2) NOT NULL,
    OHNVCNAN VARCHAR2(1000),
    OHNVCNRL VARCHAR2(1000),
    ENTDANTR NUMBER,
    OHNVTXTO VARCHAR2(1000),
    OHNVESTD NUMBER DEFAULT 1 NOT NULL,
    OHNVFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    OHNVUSAR VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_OHNV PRIMARY KEY (OHNVCDGO),
    CONSTRAINT FK_OHNV_HCNV FOREIGN KEY (HCNVCDGO) REFERENCES CNT.HCNV(HCNVCDGO),
    CONSTRAINT FK_OHNV_LNNV FOREIGN KEY (LNNVCDGO) REFERENCES CNT.LNNV(LNNVCDGO),
    CONSTRAINT CK_OHNV_TIPO CHECK (OHNVTIPO IN ('EXTRACTO', 'APORTE', 'PENDIENTE', 'SIN_DINERO')),
    CONSTRAINT CK_OHNV_FUENTE CHECK (
           (OHNVTIPO = 'EXTRACTO' AND DEXBCDGO IS NOT NULL AND APRTCDGO IS NULL AND LNNVCDGO IS NULL)
        OR (OHNVTIPO = 'APORTE' AND APRTCDGO IS NOT NULL AND DEXBCDGO IS NULL AND LNNVCDGO IS NULL)
        OR (OHNVTIPO = 'PENDIENTE' AND LNNVCDGO IS NOT NULL AND DEXBCDGO IS NULL AND APRTCDGO IS NULL)
        OR (OHNVTIPO = 'SIN_DINERO' AND DEXBCDGO IS NULL AND APRTCDGO IS NULL AND LNNVCDGO IS NULL AND OHNVTXTO IS NOT NULL)),
    CONSTRAINT CK_OHNV_VLOR CHECK (OHNVVLOR > 0),
    CONSTRAINT CK_OHNV_ESTD CHECK (OHNVESTD IN (1, 2))
);

CREATE INDEX IDX_OHNV_HCNV ON CNT.OHNV(HCNVCDGO);
CREATE INDEX IDX_OHNV_DEXB ON CNT.OHNV(DEXBCDGO);
CREATE INDEX IDX_OHNV_APRT ON CNT.OHNV(APRTCDGO);
CREATE INDEX IDX_OHNV_LNNV ON CNT.OHNV(LNNVCDGO);

COMMENT ON TABLE CNT.OHNV IS 'C34d: origen del dinero de un hecho de crédito; Σ OHNVVLOR = HCNVVLOR; un movimiento no se usa por encima de su valor';
COMMENT ON COLUMN CNT.OHNV.DEXBCDGO IS 'Línea del extracto (TSR.DEXB), sin FK';
COMMENT ON COLUMN CNT.OHNV.APRTCDGO IS 'Aporte o débito de cuenta individual (CRD.APRT), sin FK';
COMMENT ON COLUMN CNT.OHNV.LNNVCDGO IS 'Partida pendiente por regularizar (CNT.LNNV); queda resuelta por el hecho';
COMMENT ON COLUMN CNT.OHNV.OHNVCNAN IS 'Cómo está aplicado hoy (foto que arma el sistema al elegirlo)';
COMMENT ON COLUMN CNT.OHNV.OHNVCNRL IS 'Qué es en realidad (reclasificación que aplica la v8)';
COMMENT ON COLUMN CNT.OHNV.ENTDANTR IS 'Entidad a la que está aplicado hoy, si es otra que la del préstamo (CRD.ENTD), sin FK';
COMMENT ON COLUMN CNT.OHNV.OHNVTXTO IS 'Explicación (obligatoria en SIN_DINERO: lo que el partícipe queda debiendo)';


