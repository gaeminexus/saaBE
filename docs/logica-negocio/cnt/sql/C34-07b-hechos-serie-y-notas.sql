-- 1.1 Nada de C34-07b existe. ESPERADO: 0 filas.
SELECT TABLE_NAME, COLUMN_NAME FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CNT' AND (TABLE_NAME = 'NTNV' OR (TABLE_NAME = 'HCNV' AND COLUMN_NAME IN ('HCNVMSDS', 'HCNVTRDF', 'HCNVVLDF', 'HCNVDTLL'))
       OR (TABLE_NAME = 'ADNV' AND COLUMN_NAME = 'NTNVCDGO'));
-- 1.2 C34-07 aplicado. ESPERADO: 2 filas (HCNV, OHNV).
SELECT TABLE_NAME FROM ALL_TABLES WHERE OWNER = 'CNT' AND TABLE_NAME IN ('HCNV', 'OHNV') ORDER BY 1;
-- 1.3 Nombre libre. ESPERADO: 0 filas.
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE FROM ALL_OBJECTS WHERE OBJECT_NAME = 'NTNV';

-- 2. CNT.HCNV
ALTER TABLE CNT.HCNV ADD (HCNVMSDS DATE, HCNVTRDF VARCHAR2(20), HCNVVLDF NUMBER(18,2), HCNVDTLL CLOB);
ALTER TABLE CNT.HCNV DROP CONSTRAINT CK_HCNV_TIPO;
ALTER TABLE CNT.HCNV ADD CONSTRAINT CK_HCNV_TIPO CHECK (HCNVTIPO IN ('ABONO_CAPITAL', 'PAGO_CUOTAS', 'PRECANCELACION', 'REAPERTURA_CUOTAS',
    'PARTICIPE_DEBE', 'SERIE_PRECANCELACION'));
ALTER TABLE CNT.HCNV ADD CONSTRAINT CK_HCNV_TRDF CHECK (HCNVTRDF IS NULL OR HCNVTRDF IN ('NO_SE_DEBITA', 'SE_DEVUELVE', 'PARTICIPE_DEBE'));
ALTER TABLE CNT.HCNV ADD CONSTRAINT CK_HCNV_SERIE CHECK (HCNVTIPO <> 'SERIE_PRECANCELACION' OR HCNVMSDS IS NOT NULL);
COMMENT ON COLUMN CNT.HCNV.HCNVMSDS IS 'C34d: mes desde (primer día) de un hecho en serie o de las cuotas pendientes de una precancelación';
COMMENT ON COLUMN CNT.HCNV.HCNVTRDF IS 'C34d: qué pasa con la diferencia orígenes - valor: NO_SE_DEBITA, SE_DEVUELVE (sobra) o PARTICIPE_DEBE (falta)';
COMMENT ON COLUMN CNT.HCNV.HCNVVLDF IS 'C34d: diferencia orígenes - valor (positiva sobra, negativa falta)';
COMMENT ON COLUMN CNT.HCNV.HCNVDTLL IS 'C34d: reparto calculado por mes desde la tabla del SAA (JSON), lo que aplica la v8';

-- 3. CNT.NTNV — nota de ASOPREP en una novedad
CREATE TABLE CNT.NTNV (
    NTNVCDGO NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1) NOT NULL,
    NVDDCDGO NUMBER NOT NULL,
    NTNVTXTO VARCHAR2(4000) NOT NULL,
    HCNVCDGO NUMBER,
    NTNVESTD NUMBER DEFAULT 1 NOT NULL,
    NTNVFCRG TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    NTNVUSAR VARCHAR2(50) NOT NULL,
    NTNVFCAN TIMESTAMP,
    NTNVUSAN VARCHAR2(50),
    NTNVMTAN VARCHAR2(1000),
    CONSTRAINT PK_NTNV PRIMARY KEY (NTNVCDGO),
    CONSTRAINT FK_NTNV_NVDD FOREIGN KEY (NVDDCDGO) REFERENCES CNT.NVDD(NVDDCDGO),
    CONSTRAINT FK_NTNV_HCNV FOREIGN KEY (HCNVCDGO) REFERENCES CNT.HCNV(HCNVCDGO),
    CONSTRAINT CK_NTNV_ESTD CHECK (NTNVESTD IN (1, 2)),
    CONSTRAINT CK_NTNV_ANULA CHECK (NTNVESTD = 1 OR (NTNVFCAN IS NOT NULL AND NTNVUSAN IS NOT NULL AND NTNVMTAN IS NOT NULL))
);
CREATE INDEX IDX_NTNV_NVDD ON CNT.NTNV(NVDDCDGO);
CREATE INDEX IDX_NTNV_HCNV ON CNT.NTNV(HCNVCDGO);
COMMENT ON TABLE CNT.NTNV IS 'C34d: nota de ASOPREP en una novedad (respuesta escrita sin cuentas); no cambia saldos ni estados';
COMMENT ON COLUMN CNT.NTNV.HCNVCDGO IS 'Hecho de crédito en que se convirtió la nota (si se convirtió)';
COMMENT ON COLUMN CNT.NTNV.NTNVESTD IS '1 VIGENTE, 2 ANULADA';

-- 4. Adjuntos de una nota y acciones del historial
ALTER TABLE CNT.ADNV ADD (NTNVCDGO NUMBER);
ALTER TABLE CNT.ADNV ADD CONSTRAINT FK_ADNV_NTNV FOREIGN KEY (NTNVCDGO) REFERENCES CNT.NTNV(NTNVCDGO);
CREATE INDEX IDX_ADNV_NTNV ON CNT.ADNV(NTNVCDGO);
COMMENT ON COLUMN CNT.ADNV.NTNVCDGO IS 'C34d: adjunto de una nota de ASOPREP';
ALTER TABLE CNT.ADNV DROP CONSTRAINT CK_ADNV_DUENO;
ALTER TABLE CNT.ADNV ADD CONSTRAINT CK_ADNV_DUENO CHECK (NVDDCDGO IS NOT NULL OR RQNVCDGO IS NOT NULL OR RSNVCDGO IS NOT NULL
    OR DCSNCDGO IS NOT NULL OR JSNVCDGO IS NOT NULL OR HCNVCDGO IS NOT NULL OR NTNVCDGO IS NOT NULL);
ALTER TABLE CNT.HSNV DROP CONSTRAINT CK_HSNV_ACCN;
ALTER TABLE CNT.HSNV ADD CONSTRAINT CK_HSNV_ACCN CHECK (HSNVACCN IN ('CARGA', 'EDICION', 'ENVIO', 'RESPUESTA', 'ACEPTACION', 'OBSERVACION',
    'NO_EXISTE', 'NO_APLICA', 'APLICACION', 'AJUSTE', 'VINCULO', 'DESVINCULO', 'DECISION', 'ADJUNTO',
    'COPIA_EXPEDIENTE', 'CIERRE', 'REAPERTURA', 'ANULACION', 'REEMPLAZO',
    'JUSTIFICACION', 'ANULA_JUSTIFICACION', 'CONOCIDA', 'ANULA_RESPUESTA', 'HECHO_CREDITO', 'ANULA_HECHO', 'NOTA', 'ANULA_NOTA'));

-- 5. Después. ESPERADO: HCNV 20 columnas; NTNV 10; ADNV con NTNVCDGO; reglas ENABLED / VALIDATED.
SELECT TABLE_NAME, COUNT(*) COLUMNAS FROM ALL_TAB_COLUMNS WHERE OWNER = 'CNT' AND TABLE_NAME IN ('HCNV', 'NTNV') GROUP BY TABLE_NAME ORDER BY 1;
SELECT COUNT(*) ADNV_NTNV FROM ALL_TAB_COLUMNS WHERE OWNER = 'CNT' AND TABLE_NAME = 'ADNV' AND COLUMN_NAME = 'NTNVCDGO';
SELECT CONSTRAINT_NAME, STATUS, VALIDATED FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CNT' AND CONSTRAINT_NAME IN ('CK_HCNV_TIPO', 'CK_HCNV_TRDF', 'CK_HCNV_SERIE', 'PK_NTNV', 'FK_NTNV_NVDD', 'FK_NTNV_HCNV',
       'CK_NTNV_ESTD', 'CK_NTNV_ANULA', 'FK_ADNV_NTNV', 'CK_ADNV_DUENO', 'CK_HSNV_ACCN') ORDER BY 1;

