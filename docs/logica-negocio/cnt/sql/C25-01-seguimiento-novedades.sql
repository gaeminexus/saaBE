-- BLOQUE 1 — CONTROLES ANTES
-- 1.1 Ninguna de las siete tablas existe. ESPERADO: 0 filas.
SELECT OWNER, TABLE_NAME
  FROM ALL_TABLES
 WHERE OWNER = 'CNT'
   AND TABLE_NAME IN ('DCSN', 'NVDD', 'RQNV', 'RSNV', 'ADNV', 'VNNV', 'HSNV');

-- 1.2 Las tablas padre existen. ESPERADO: 4 filas (CNT.ASNT, CNT.DTAS, CNT.PRDO, SCP.PJRQ).
SELECT OWNER, TABLE_NAME
  FROM ALL_TABLES
 WHERE (OWNER = 'CNT' AND TABLE_NAME IN ('ASNT', 'DTAS', 'PRDO'))
    OR (OWNER = 'SCP' AND TABLE_NAME = 'PJRQ');

-- 1.3 Ninguna restricción ni índice con los nombres nuevos. ESPERADO: 0 filas.
SELECT OWNER, INDEX_NAME AS NOMBRE FROM ALL_INDEXES
 WHERE OWNER = 'CNT' AND (INDEX_NAME LIKE 'IDX_NVDD%' OR INDEX_NAME LIKE 'IDX_RQNV%' OR INDEX_NAME LIKE 'IDX_RSNV%'
       OR INDEX_NAME LIKE 'IDX_ADNV%' OR INDEX_NAME LIKE 'IDX_VNNV%' OR INDEX_NAME LIKE 'IDX_HSNV%' OR INDEX_NAME LIKE 'UK_VNNV%')
UNION ALL
SELECT OWNER, CONSTRAINT_NAME FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CNT' AND REGEXP_LIKE(CONSTRAINT_NAME, '^(PK|FK|UK|CK)_(DCSN|NVDD|RQNV|RSNV|ADNV|VNNV|HSNV)');


