-- ⛔ VA ANTES DEL WAR de la rama cuadre/c25-seguimiento-novedades: Hibernate valida las entidades nuevas contra
--    estas tablas. Con el WAR anterior las tablas no hacen daño: nadie las lee.
--
-- SQL PURO (sin SET/DEFINE/WHENEVER). Solo DDL (commit implícito). Idempotente por control: si el CONTROL 1
-- devuelve filas, NO correr (las tablas ya existen). Sin datos: las decisiones y las novedades se cargan con
-- C25-02/C25-03 del expediente o con POST /nvdd/cargaLote y POST /nvdd/cargaDecisiones.
