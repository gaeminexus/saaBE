--   - Sin relación usuario -> área (D-056 (5)): el área es dato del requerimiento (RQNVARRS) y de la respuesta.
--   - VNNV: índice único funcional sobre los vínculos ACTIVOS (no se vincula dos veces el mismo asiento a la misma
--     novedad con el mismo tipo); un asiento de ajuste se anula (VNNVESTD = 2), no se borra.
--   - HSNV: más acciones (NO_EXISTE, NO_APLICA, AJUSTE, VINCULO, DESVINCULO, DECISION, ADJUNTO, COPIA_EXPEDIENTE).
--   - PRRGCDGO (partida de C22) queda sin FK: C22 no está programado; el bloque 9 la agrega cuando exista CNT.PRRG.
--     Mientras tanto C25 lee el saldo de las cuentas por regularizar directamente de CNT.DTAS.
