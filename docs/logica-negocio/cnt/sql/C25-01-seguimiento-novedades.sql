-- 9.1 (DECISIVO) Las siete tablas existen. ESPERADO: 7 filas.
SELECT OWNER, TABLE_NAME
  FROM ALL_TABLES
 WHERE OWNER = 'CNT'
   AND TABLE_NAME IN ('DCSN', 'NVDD', 'RQNV', 'RSNV', 'ADNV', 'VNNV', 'HSNV')
 ORDER BY TABLE_NAME;

-- 9.2 Restricciones por tipo. ESPERADO: todas ENABLED; P = 7, R = 18, U = 3 (DCSN, NVDD, RQNV).
SELECT CONSTRAINT_TYPE, COUNT(*) AS CANTIDAD, MIN(STATUS) AS STATUS_MIN, MAX(STATUS) AS STATUS_MAX
  FROM ALL_CONSTRAINTS
 WHERE OWNER = 'CNT'
   AND TABLE_NAME IN ('DCSN', 'NVDD', 'RQNV', 'RSNV', 'ADNV', 'VNNV', 'HSNV')
   AND CONSTRAINT_TYPE IN ('P', 'R', 'U')
 GROUP BY CONSTRAINT_TYPE
 ORDER BY CONSTRAINT_TYPE;

