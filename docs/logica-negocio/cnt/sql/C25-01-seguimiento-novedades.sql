SELECT TABLE_NAME, COUNT(*) AS COLUMNAS
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'CNT'
   AND TABLE_NAME IN ('DCSN', 'NVDD', 'RQNV', 'RSNV', 'ADNV', 'VNNV', 'HSNV')
 GROUP BY TABLE_NAME
 ORDER BY TABLE_NAME;


